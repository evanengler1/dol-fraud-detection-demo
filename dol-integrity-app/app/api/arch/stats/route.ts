import { handle } from "@/lib/server/route"
import { queryPlatform } from "@/lib/server/db"

export const dynamic = "force-dynamic"

/** Live stats for the architecture page: one round trip for counts, one for DT refresh, one for tasks. */
export async function GET(req: Request) {
  return handle(req, async () => {
    const [counts, dts, tasks] = await Promise.all([
      queryPlatform(
        `SELECT
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.ETA_539_WEEKLY_CLAIMS) AS ETA_539,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.ETA_227_OVERPAYMENTS) AS ETA_227,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.ETA_5159_PAYMENTS) AS ETA_5159,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.ETA_902P_PUA) AS ETA_902P,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.BAM_INTEGRITY_RATES) AS BAM,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.FORM_5500) AS FORM_5500,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.OFLC_H2_CASES) AS OFLC,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.WHD_CASE) AS WHD,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.OSHA_INSPECTION) AS OSHA,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.ITA_300A) AS ITA,
          (SELECT COUNT(DISTINCT FILE_NAME) FROM DOL_FRAUD_DEMO.AI.POLICY_DOC_CHUNKS) AS POLICY_DOCS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.AI.POLICY_DOC_CHUNKS) AS POLICY_CHUNKS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM) AS SYNTH_CLAIMS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_PAYMENT) AS SYNTH_PAYMENTS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_SOURCE_RECORD) AS ER_SOURCE_RECORDS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_MASTER) AS ER_EMPLOYERS,
          (SELECT COUNT_IF(AGENCY_COUNT >= 2) FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_MASTER) AS ER_MULTI_AGENCY,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360) AS RISK_360_ROWS,
          (SELECT COUNT_IF(AGENCIES_FLAGGED >= 2) FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360) AS RISK_CROSS_AGENCY,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ML.CLAIMS_ANOMALIES WHERE IS_ANOMALY) AS ML_ANOMALIES,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ML.CLAIM_ML_SCORES) AS ML_SCORED,
          (SELECT METRIC_VALUE FROM DOL_FRAUD_DEMO.ML.CLAIM_MODEL_METRICS WHERE ERROR_METRIC = 'auc' LIMIT 1) AS ML_AUC,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ML.FRAUD_OP_FORECAST) AS ML_FORECAST_ROWS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.AI.COMPLAINT_ENRICHED) AS AI_COMPLAINTS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.AI.OSHA_NARRATIVE_ENRICHED) AS AI_NARRATIVES,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.AI.EMPLOYER_CASE_BRIEF) AS AI_BRIEFS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG) AS ALERTS_FIRED,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.APP.CASE_ACTIONS) AS APP_ACTIONS,
          (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.APP.REFERRALS) AS APP_REFERRALS`,
        { long: true },
      ),
      queryPlatform(
        `SELECT NAME, STATE, REFRESH_ACTION, REFRESH_TRIGGER, REFRESH_START_TIME, REFRESH_END_TIME, DATA_TIMESTAMP
         FROM TABLE(DOL_FRAUD_DEMO.INFORMATION_SCHEMA.DYNAMIC_TABLE_REFRESH_HISTORY(RESULT_LIMIT => 200))
         QUALIFY ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY REFRESH_START_TIME DESC NULLS LAST) = 1`,
      ),
      queryPlatform(
        `SELECT NAME, STATE, SCHEDULED_TIME, COMPLETED_TIME, ERROR_MESSAGE
         FROM TABLE(DOL_FRAUD_DEMO.INFORMATION_SCHEMA.TASK_HISTORY(RESULT_LIMIT => 50))
         QUALIFY ROW_NUMBER() OVER (PARTITION BY NAME ORDER BY SCHEDULED_TIME DESC) = 1`,
      ),
    ])
    return { counts: counts[0] ?? {}, dynamicTables: dts, tasks }
  })
}
