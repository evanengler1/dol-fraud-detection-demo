-- =============================================================================
-- 00_setup.sql — DOL OSHA Demo: Phase 1 Infrastructure (idempotent)
-- Recreates all objects from scratch. Run as ACCOUNTADMIN or a role with
-- CREATE DATABASE, CREATE WAREHOUSE, CREATE ROLE, CREATE INTEGRATION privileges.
-- =============================================================================

USE ROLE ACCOUNTADMIN;

-- Warehouse
CREATE WAREHOUSE IF NOT EXISTS DOL_OSHA_WH
    WAREHOUSE_SIZE = 'XSMALL'
    AUTO_SUSPEND = 60
    AUTO_RESUME = TRUE;

-- Role
CREATE ROLE IF NOT EXISTS DOL_OSHA_DEMO_ROLE;
GRANT USAGE ON WAREHOUSE DOL_OSHA_WH TO ROLE DOL_OSHA_DEMO_ROLE;
GRANT ROLE DOL_OSHA_DEMO_ROLE TO ROLE SYSADMIN;

-- Database + schemas
CREATE DATABASE IF NOT EXISTS DOL_OSHA_DEMO;
GRANT OWNERSHIP ON DATABASE DOL_OSHA_DEMO TO ROLE DOL_OSHA_DEMO_ROLE COPY CURRENT GRANTS;

USE ROLE DOL_OSHA_DEMO_ROLE;
USE WAREHOUSE DOL_OSHA_WH;
USE DATABASE DOL_OSHA_DEMO;

CREATE SCHEMA IF NOT EXISTS RAW;
CREATE SCHEMA IF NOT EXISTS TRANSFORMED;
CREATE SCHEMA IF NOT EXISTS ANALYTICS;

USE SCHEMA RAW;

-- Storage integration (requires ACCOUNTADMIN)
-- Already exists: DOL_S3_INT
-- CREATE OR REPLACE STORAGE INTEGRATION DOL_S3_INT
--     TYPE = EXTERNAL_STAGE
--     STORAGE_PROVIDER = 'S3'
--     STORAGE_AWS_ROLE_ARN = 'arn:aws:iam::<AWS_ACCOUNT_ID>:role/<SNOWFLAKE_READER_ROLE>'
--     ENABLED = TRUE
--     STORAGE_ALLOWED_LOCATIONS = ('s3://YOUR-BUCKET/');

-- External stage
CREATE OR REPLACE STAGE OSHA_S3_STAGE
    URL = 's3://YOUR-BUCKET/osha-raw/'
    STORAGE_INTEGRATION = DOL_S3_INT
    FILE_FORMAT = (
        TYPE = CSV
        SKIP_HEADER = 1
        FIELD_OPTIONALLY_ENCLOSED_BY = '"'
        NULL_IF = ('', 'NULL')
        EMPTY_FIELD_AS_NULL = TRUE
        MULTI_LINE = TRUE
    );

