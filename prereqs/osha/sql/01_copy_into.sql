-- =============================================================================
-- 01_copy_into.sql — Load raw CSV data from S3 stage into RAW tables
-- Prerequisite: 00_setup.sql has been run; CSV files exist on S3 stage.
-- =============================================================================

USE ROLE DOL_OSHA_DEMO_ROLE;
USE WAREHOUSE DOL_OSHA_WH;
USE DATABASE DOL_OSHA_DEMO;
USE SCHEMA RAW;

COPY INTO INSPECTION
FROM @OSHA_S3_STAGE/inspection/
FILE_FORMAT = (TYPE = CSV SKIP_HEADER = 1 FIELD_OPTIONALLY_ENCLOSED_BY = '"'
               NULL_IF = ('', 'NULL') EMPTY_FIELD_AS_NULL = TRUE MULTI_LINE = TRUE)
ON_ERROR = CONTINUE
ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

