-- =============================================================================
-- 02_transformed_tables.sql — RAW → TRANSFORMED with proper types
-- Casts all VARCHAR columns, cleans data, filters deleted violations,
-- and adds computed columns. Run after 01_copy_into.sql.
-- =============================================================================

USE ROLE DOL_OSHA_DEMO_ROLE;
USE WAREHOUSE DOL_OSHA_WH;
USE DATABASE DOL_OSHA_DEMO;

CREATE SCHEMA IF NOT EXISTS TRANSFORMED;
USE SCHEMA TRANSFORMED;

-- =============================================================================
-- INSPECTION
-- =============================================================================
CREATE OR REPLACE TABLE INSPECTION AS
SELECT
    TRY_TO_NUMBER(NULLIF(TRIM(r.ACTIVITY_NR), ''), 12, 0)        AS ACTIVITY_NR,
    TRY_TO_NUMBER(NULLIF(TRIM(r.REPORTING_ID), ''), 12, 0)       AS REPORTING_ID,
    CAST(NULLIF(TRIM(r.STATE_FLAG), '') AS VARCHAR(2))            AS STATE_FLAG,
    CAST(TRIM(r.ESTAB_NAME) AS VARCHAR(300))                      AS ESTAB_NAME,
    CAST(TRIM(r.SITE_ADDRESS) AS VARCHAR(300))                    AS SITE_ADDRESS,
    CAST(TRIM(r.SITE_CITY) AS VARCHAR(100))                       AS SITE_CITY,
    CAST(NULLIF(TRIM(r.SITE_STATE), '') AS VARCHAR(2))            AS SITE_STATE,
    CAST(NULLIF(TRIM(r.SITE_ZIP), '') AS VARCHAR(10))             AS SITE_ZIP,
    CAST(NULLIF(TRIM(r.OWNER_TYPE), '') AS VARCHAR(1))            AS OWNER_TYPE,
    CAST(NULLIF(TRIM(r.OWNER_CODE), '') AS VARCHAR(10))           AS OWNER_CODE,
    CASE WHEN UPPER(TRIM(r.ADV_NOTICE)) = 'Y' THEN TRUE
         WHEN UPPER(TRIM(r.ADV_NOTICE)) = 'N' THEN FALSE
         ELSE NULL END                                            AS ADV_NOTICE,
    CAST(NULLIF(TRIM(r.SAFETY_HLTH), '') AS VARCHAR(1))           AS SAFETY_HLTH,
    CAST(NULLIF(TRIM(r.SIC_CODE), '') AS VARCHAR(6))              AS SIC_CODE,
    CAST(NULLIF(TRIM(r.NAICS_CODE), '') AS VARCHAR(8))            AS NAICS_CODE,
    CAST(NULLIF(TRIM(r.INSP_TYPE), '') AS VARCHAR(1))             AS INSP_TYPE,
    CAST(NULLIF(TRIM(r.INSP_SCOPE), '') AS VARCHAR(1))            AS INSP_SCOPE,
    CAST(NULLIF(TRIM(r.WHY_NO_INSP), '') AS VARCHAR(1))           AS WHY_NO_INSP,
    CAST(NULLIF(TRIM(r.UNION_STATUS), '') AS VARCHAR(1))          AS UNION_STATUS,
    CASE WHEN TRIM(r.SAFETY_MANUF) = 'X' THEN TRUE ELSE FALSE END AS SAFETY_MANUF,
    CASE WHEN TRIM(r.SAFETY_CONST) = 'X' THEN TRUE ELSE FALSE END AS SAFETY_CONST,
    CASE WHEN TRIM(r.SAFETY_MARIT) = 'X' THEN TRUE ELSE FALSE END AS SAFETY_MARIT,
    CASE WHEN TRIM(r.HEALTH_MANUF) = 'X' THEN TRUE ELSE FALSE END AS HEALTH_MANUF,
    CASE WHEN TRIM(r.HEALTH_CONST) = 'X' THEN TRUE ELSE FALSE END AS HEALTH_CONST,
    CASE WHEN TRIM(r.HEALTH_MARIT) = 'X' THEN TRUE ELSE FALSE END AS HEALTH_MARIT,
    CASE WHEN UPPER(TRIM(r.MIGRANT)) = 'Y' THEN TRUE
         WHEN UPPER(TRIM(r.MIGRANT)) = 'N' THEN FALSE
         ELSE NULL END                                            AS MIGRANT,
    CAST(TRIM(r.MAIL_STREET) AS VARCHAR(300))                     AS MAIL_STREET,
    CAST(TRIM(r.MAIL_CITY) AS VARCHAR(100))                       AS MAIL_CITY,
    CAST(NULLIF(TRIM(r.MAIL_STATE), '') AS VARCHAR(2))            AS MAIL_STATE,
    CAST(NULLIF(TRIM(r.MAIL_ZIP), '') AS VARCHAR(10))             AS MAIL_ZIP,
    CAST(NULLIF(TRIM(r.HOST_EST_KEY), '') AS VARCHAR(50))         AS HOST_EST_KEY,
    TRY_TO_NUMBER(NULLIF(TRIM(r.NR_IN_ESTAB), ''), 8, 0)        AS NR_IN_ESTAB,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.OPEN_DATE), ''))::TIMESTAMP_NTZ        AS OPEN_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.CASE_MOD_DATE), ''))::TIMESTAMP_NTZ    AS CASE_MOD_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.CLOSE_CONF_DATE), ''))::TIMESTAMP_NTZ  AS CLOSE_CONF_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.CLOSE_CASE_DATE), ''))::TIMESTAMP_NTZ  AS CLOSE_CASE_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.LOAD_DT), ''))::TIMESTAMP_NTZ         AS LOAD_DT,
    r._LOADED_AT,
    -- Computed columns
    DATEDIFF('day',
        TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.OPEN_DATE), ''))::TIMESTAMP_NTZ,
        TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.CLOSE_CASE_DATE), ''))::TIMESTAMP_NTZ
    )                                                             AS DAYS_TO_CLOSE
FROM DOL_OSHA_DEMO.RAW.INSPECTION r;

-- =============================================================================
-- VIOLATION (filters out DELETE_FLAG = 'X')
-- =============================================================================
CREATE OR REPLACE TABLE VIOLATION AS
SELECT
    TRY_TO_NUMBER(NULLIF(TRIM(r.ACTIVITY_NR), ''), 12, 0)        AS ACTIVITY_NR,
    CAST(NULLIF(TRIM(r.CITATION_ID), '') AS VARCHAR(20))          AS CITATION_ID,
    CAST(NULLIF(TRIM(r.STANDARD), '') AS VARCHAR(50))             AS STANDARD,
    CAST(NULLIF(TRIM(r.VIOL_TYPE), '') AS VARCHAR(1))             AS VIOL_TYPE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.ISSUANCE_DATE), ''))::TIMESTAMP_NTZ    AS ISSUANCE_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.ABATE_DATE), ''))::TIMESTAMP_NTZ       AS ABATE_DATE,
    CAST(NULLIF(TRIM(r.ABATE_COMPLETE), '') AS VARCHAR(1))        AS ABATE_COMPLETE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.CURRENT_PENALTY), ''), 12, 2)    AS CURRENT_PENALTY,
    TRY_TO_NUMBER(NULLIF(TRIM(r.INITIAL_PENALTY), ''), 12, 2)    AS INITIAL_PENALTY,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.CONTEST_DATE), ''))::TIMESTAMP_NTZ     AS CONTEST_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.FINAL_ORDER_DATE), ''))::TIMESTAMP_NTZ AS FINAL_ORDER_DATE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.NR_INSTANCES), ''), 8, 0)        AS NR_INSTANCES,
    TRY_TO_NUMBER(NULLIF(TRIM(r.NR_EXPOSED), ''), 8, 0)          AS NR_EXPOSED,
    TRY_TO_NUMBER(NULLIF(TRIM(r.REC), ''), 4, 0)                 AS REC,
    TRY_TO_NUMBER(NULLIF(TRIM(r.GRAVITY), ''), 4, 0)             AS GRAVITY,
    CASE WHEN TRIM(r.EMPHASIS) = 'X' THEN TRUE ELSE FALSE END    AS EMPHASIS,
    CAST(NULLIF(TRIM(r.HAZCAT), '') AS VARCHAR(20))               AS HAZCAT,
    TRY_TO_NUMBER(NULLIF(TRIM(r.FTA_INSP_NR), ''), 12, 0)       AS FTA_INSP_NR,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.FTA_ISSUANCE_DATE), ''))::TIMESTAMP_NTZ AS FTA_ISSUANCE_DATE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.FTA_PENALTY), ''), 12, 2)        AS FTA_PENALTY,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.FTA_CONTEST_DATE), ''))::TIMESTAMP_NTZ  AS FTA_CONTEST_DATE,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.FTA_FINAL_ORDER_DATE), ''))::TIMESTAMP_NTZ AS FTA_FINAL_ORDER_DATE,
    CAST(NULLIF(TRIM(r.HAZSUB1), '') AS VARCHAR(50))              AS HAZSUB1,
    CAST(NULLIF(TRIM(r.HAZSUB2), '') AS VARCHAR(50))              AS HAZSUB2,
    CAST(NULLIF(TRIM(r.HAZSUB3), '') AS VARCHAR(50))              AS HAZSUB3,
    CAST(NULLIF(TRIM(r.HAZSUB4), '') AS VARCHAR(50))              AS HAZSUB4,
    CAST(NULLIF(TRIM(r.HAZSUB5), '') AS VARCHAR(50))              AS HAZSUB5,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.LOAD_DT), ''))::TIMESTAMP_NTZ          AS LOAD_DT,
    r._LOADED_AT,
    -- Computed columns
    TRY_TO_NUMBER(NULLIF(TRIM(r.INITIAL_PENALTY), ''), 12, 2)
      - TRY_TO_NUMBER(NULLIF(TRIM(r.CURRENT_PENALTY), ''), 12, 2) AS PENALTY_REDUCTION
FROM DOL_OSHA_DEMO.RAW.VIOLATION r
WHERE NULLIF(TRIM(r.DELETE_FLAG), '') IS NULL;  -- exclude deleted violations

-- =============================================================================
-- VIOLATION_EVENT
-- =============================================================================
CREATE OR REPLACE TABLE VIOLATION_EVENT AS
SELECT
    TRY_TO_NUMBER(NULLIF(TRIM(r.ACTIVITY_NR), ''), 12, 0)        AS ACTIVITY_NR,
    CAST(NULLIF(TRIM(r.CITATION_ID), '') AS VARCHAR(20))          AS CITATION_ID,
    CAST(NULLIF(TRIM(r.PEN_FTA), '') AS VARCHAR(1))               AS PEN_FTA,
    CAST(NULLIF(TRIM(r.HIST_EVENT), '') AS VARCHAR(1))            AS HIST_EVENT,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.HIST_DATE), ''))::TIMESTAMP_NTZ        AS HIST_DATE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.HIST_PENALTY), ''), 12, 2)       AS HIST_PENALTY,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.HIST_ABATE_DATE), ''))::TIMESTAMP_NTZ  AS HIST_ABATE_DATE,
    CAST(NULLIF(TRIM(r.HIST_VTYPE), '') AS VARCHAR(1))            AS HIST_VTYPE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.HIST_INSP_NR), ''), 12, 0)      AS HIST_INSP_NR,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.LOAD_DT), ''))::TIMESTAMP_NTZ          AS LOAD_DT,
    r._LOADED_AT
FROM DOL_OSHA_DEMO.RAW.VIOLATION_EVENT r;

-- =============================================================================
-- ACCIDENT
-- =============================================================================
CREATE OR REPLACE TABLE ACCIDENT AS
SELECT
    TRY_TO_NUMBER(NULLIF(TRIM(r.SUMMARY_NR), ''), 12, 0)         AS SUMMARY_NR,
    CAST(NULLIF(TRIM(r.REPORT_ID), '') AS VARCHAR(20))            AS REPORT_ID,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.EVENT_DATE), ''))::TIMESTAMP_NTZ       AS EVENT_DATE,
    CAST(NULLIF(TRIM(r.EVENT_TIME), '') AS VARCHAR(10))           AS EVENT_TIME,
    CAST(TRIM(r.EVENT_DESC) AS VARCHAR(4000))                     AS EVENT_DESC,
    CAST(TRIM(r.EVENT_KEYWORD) AS VARCHAR(1000))                  AS EVENT_KEYWORD,
    CAST(NULLIF(TRIM(r.CONST_END_USE), '') AS VARCHAR(2))         AS CONST_END_USE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.BUILD_STORIES), ''), 6, 1)       AS BUILD_STORIES,
    TRY_TO_NUMBER(NULLIF(TRIM(r.NONBUILD_HT), ''), 6, 1)        AS NONBUILD_HT,
    CAST(NULLIF(TRIM(r.PROJECT_COST), '') AS VARCHAR(2))          AS PROJECT_COST,
    CAST(NULLIF(TRIM(r.PROJECT_TYPE), '') AS VARCHAR(2))          AS PROJECT_TYPE,
    CAST(NULLIF(TRIM(r.SIC_LIST), '') AS VARCHAR(100))            AS SIC_LIST,
    CASE WHEN TRIM(r.FATALITY) = 'X' THEN TRUE ELSE FALSE END    AS FATALITY,
    CAST(NULLIF(TRIM(r.STATE_FLAG), '') AS VARCHAR(2))            AS STATE_FLAG,
    CAST(TRIM(r.ABSTRACT_TEXT) AS VARCHAR(8000))                  AS ABSTRACT_TEXT,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.LOAD_DT), ''))::TIMESTAMP_NTZ          AS LOAD_DT,
    r._LOADED_AT
FROM DOL_OSHA_DEMO.RAW.ACCIDENT r;

-- =============================================================================
-- ACCIDENT_INJURY
-- =============================================================================
CREATE OR REPLACE TABLE ACCIDENT_INJURY AS
SELECT
    TRY_TO_NUMBER(NULLIF(TRIM(r.SUMMARY_NR), ''), 12, 0)         AS SUMMARY_NR,
    TRY_TO_NUMBER(NULLIF(TRIM(r.REL_INSP_NR), ''), 12, 0)       AS REL_INSP_NR,
    NULLIF(TRY_TO_NUMBER(NULLIF(TRIM(r.AGE), ''), 4, 0), 0)     AS AGE,  -- 0 = unknown → NULL
    CAST(NULLIF(TRIM(r.SEX), '') AS VARCHAR(1))                   AS SEX,
    TRY_TO_NUMBER(NULLIF(TRIM(r.NATURE_OF_INJ), ''), 4, 0)      AS NATURE_OF_INJ,
    TRY_TO_NUMBER(NULLIF(TRIM(r.PART_OF_BODY), ''), 4, 0)       AS PART_OF_BODY,
    TRY_TO_NUMBER(NULLIF(TRIM(r.SRC_OF_INJURY), ''), 4, 0)      AS SRC_OF_INJURY,
    TRY_TO_NUMBER(NULLIF(TRIM(r.EVENT_TYPE), ''), 4, 0)         AS EVENT_TYPE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.EVN_FACTOR), ''), 4, 0)         AS EVN_FACTOR,
    TRY_TO_NUMBER(NULLIF(TRIM(r.HUM_FACTOR), ''), 4, 0)         AS HUM_FACTOR,
    CAST(NULLIF(TRIM(r.OCC_CODE), '') AS VARCHAR(10))             AS OCC_CODE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.DEGREE_OF_INJ), ''), 4, 0)      AS DEGREE_OF_INJ,
    TRY_TO_NUMBER(NULLIF(TRIM(r.TASK_ASSIGNED), ''), 4, 0)      AS TASK_ASSIGNED,
    CAST(NULLIF(TRIM(r.HAZSUB), '') AS VARCHAR(50))               AS HAZSUB,
    TRY_TO_NUMBER(NULLIF(TRIM(r.CONST_OP), ''), 4, 0)           AS CONST_OP,
    TRY_TO_NUMBER(NULLIF(TRIM(r.CONST_OP_CAUSE), ''), 4, 0)     AS CONST_OP_CAUSE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.FAT_CAUSE), ''), 4, 0)          AS FAT_CAUSE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.FALL_DISTANCE), ''), 6, 1)      AS FALL_DISTANCE,
    TRY_TO_NUMBER(NULLIF(TRIM(r.FALL_HT), ''), 6, 1)            AS FALL_HT,
    TRY_TO_NUMBER(NULLIF(TRIM(r.INJURY_LINE_NR), ''), 4, 0)     AS INJURY_LINE_NR,
    TRY_TO_TIMESTAMP_TZ(NULLIF(TRIM(r.LOAD_DT), ''))::TIMESTAMP_NTZ          AS LOAD_DT,
    r._LOADED_AT
FROM DOL_OSHA_DEMO.RAW.ACCIDENT_INJURY r;
