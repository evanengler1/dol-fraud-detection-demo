-- Phase 1: infrastructure for the DOL WHD demo.
USE ROLE ACCOUNTADMIN;

CREATE ROLE IF NOT EXISTS DOL_WHD_DEMO_ROLE;
SET my_user = CURRENT_USER();
GRANT ROLE DOL_WHD_DEMO_ROLE TO USER IDENTIFIER($my_user);
GRANT ROLE DOL_WHD_DEMO_ROLE TO ROLE SYSADMIN;

CREATE WAREHOUSE IF NOT EXISTS DOL_WHD_WH
    WAREHOUSE_SIZE = XSMALL AUTO_SUSPEND = 60 AUTO_RESUME = TRUE INITIALLY_SUSPENDED = TRUE;
CREATE DATABASE IF NOT EXISTS DOL_WHD_DEMO;
CREATE SCHEMA IF NOT EXISTS DOL_WHD_DEMO.RAW;

GRANT OWNERSHIP ON WAREHOUSE DOL_WHD_WH TO ROLE DOL_WHD_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON DATABASE DOL_WHD_DEMO TO ROLE DOL_WHD_DEMO_ROLE COPY CURRENT GRANTS;
GRANT OWNERSHIP ON SCHEMA DOL_WHD_DEMO.RAW TO ROLE DOL_WHD_DEMO_ROLE COPY CURRENT GRANTS;

