-- Phase 1: file format and external stage. No NULL/blank normalization here; values land as delivered.
USE ROLE DOL_WHD_DEMO_ROLE;
USE WAREHOUSE DOL_WHD_WH;
USE SCHEMA DOL_WHD_DEMO.RAW;

CREATE OR REPLACE FILE FORMAT RAW.WHD_CSV_FF
    TYPE = CSV
    SKIP_HEADER = 1
    FIELD_OPTIONALLY_ENCLOSED_BY = '"'
    ERROR_ON_COLUMN_COUNT_MISMATCH = FALSE;

CREATE OR REPLACE STAGE RAW.WHD_S3_STAGE
    URL = 's3://YOUR-BUCKET/whd-raw/'
    STORAGE_INTEGRATION = DOL_S3_INT
    FILE_FORMAT = RAW.WHD_CSV_FF;
