       CONTEST_DATE::DATE AS CONTEST_DATE, FINAL_ORDER_DATE::DATE AS FINAL_ORDER_DATE
FROM DOL_OSHA_DEMO.TRANSFORMED.VIOLATION;

CREATE OR REPLACE VIEW OSHA_ACCIDENT COMMENT = 'Public: OSHA accident investigations with narratives (DOL_OSHA_DEMO + accident_abstract)' AS
SELECT a.SUMMARY_NR, ai.REL_INSP_NR AS ACTIVITY_NR, a.EVENT_DATE::DATE AS EVENT_DATE,
       a.EVENT_DESC, a.EVENT_KEYWORD, a.FATALITY, n.ABSTRACT_TEXT
FROM DOL_OSHA_DEMO.TRANSFORMED.ACCIDENT a
LEFT JOIN (SELECT SUMMARY_NR, MIN(REL_INSP_NR) AS REL_INSP_NR
           FROM DOL_OSHA_DEMO.TRANSFORMED.ACCIDENT_INJURY GROUP BY 1) ai ON ai.SUMMARY_NR = a.SUMMARY_NR
LEFT JOIN OSHA_ACCIDENT_NARRATIVE n ON n.SUMMARY_NR = a.SUMMARY_NR;

