-- BAM / PIIA integrity rates by state and quarter (Jul 2019 - Jun 2024) -----------
-- Column positions follow the workbook's stacked header (header row 10):
--   SAMPLE, PAID_BAM, PROPER = OP rate, PROPER_1 = OP $, WARNINGS/_1 = OP rate/$ excl. warnings,
--   RATE = fraud rate, DOLLARS = fraud $, RATE_1/DOLLARS_1 = BYE, RATE_2/DOLLARS_2 = operational
CREATE OR REPLACE TABLE BAM_INTEGRITY_RATES COMMENT = 'Public: BAM/PIIA overpayment and fraud rates by state and quarter (oui.doleta.gov bam/2024)' AS
SELECT ST AS STATE_CODE,
       QTR AS YEAR_QTR,
       TRY_TO_NUMBER(SPLIT_PART(QTR, '.', 1))              AS YEAR,
       TRY_TO_NUMBER(SPLIT_PART(QTR, '.', 2))              AS QUARTER,
       TRY_TO_NUMBER("SAMPLE")                               AS BAM_SAMPLE_SIZE,
       TRY_TO_DECIMAL(PAID_BAM, 18, 0)                     AS BENEFITS_PAID,
       TRY_TO_DECIMAL(PROPER, 10, 5)                       AS OVERPAYMENT_RATE,
       TRY_TO_DECIMAL(PROPER_1, 18, 0)                     AS OVERPAYMENT_DOLLARS,
       TRY_TO_DECIMAL(RATE, 10, 5)                         AS FRAUD_RATE,
       TRY_TO_DECIMAL(DOLLARS, 18, 0)                      AS FRAUD_DOLLARS,
       TRY_TO_DECIMAL(RATE_2, 10, 5)                       AS OPERATIONAL_RATE,
       _SOURCE_FILE, _LOADED_AT
FROM DOL_FRAUD_DEMO.RAW_PUBLIC.BAM_RATES_BY_QTR_STATE
WHERE ST IS NOT NULL AND TRY_TO_DECIMAL(PROPER, 10, 5) IS NOT NULL
  AND TRY_TO_NUMBER(SPLIT_PART(QTR, '.', 2)) IS NOT NULL;   -- drops Mean / Stand Dev summary rows

-- BAM fraud overpayments by cause (PIIA 2024: CY23 Q3 - CY24 Q2) ------------------
CREATE OR REPLACE TABLE BAM_FRAUD_BY_CAUSE COMMENT = 'Public: BAM PIIA 2024 estimated fraud overpayments by cause and state' AS
SELECT ST AS STATE_CODE, TRIM(CAUSE) AS CAUSE,
       TRY_TO_DECIMAL(DOLLARS_PAID, 10, 6) AS PCT_OF_DOLLARS_PAID,
       TRY_TO_DECIMAL(DOLLARS_OP, 10, 6)   AS PCT_OF_FRAUD_OP,
       TRY_TO_DECIMAL(AMOUNT, 18, 0)       AS ESTIMATED_FRAUD_DOLLARS,
       _SOURCE_FILE, _LOADED_AT
FROM DOL_FRAUD_DEMO.RAW_PUBLIC.BAM_FRAUD_BY_CAUSE
WHERE CAUSE IS NOT NULL AND ST IS NOT NULL AND LENGTH(ST) = 2;

-- OSHA ITA 300A establishment summaries (EIN-bearing), 2024 + 2025 filings --------
CREATE OR REPLACE TABLE ITA_300A COMMENT = 'Public: OSHA ITA Form 300A establishment injury summaries (osha.gov), CY2024-CY2025' AS
SELECT TRY_TO_NUMBER(ID) AS ITA_ID,
       ESTABLISHMENT_ID, ESTABLISHMENT_NAME, COMPANY_NAME,
       NULLIF(LPAD(REGEXP_REPLACE(EIN, '[^0-9]', ''), 9, '0'), '000000000') AS EIN,
       STREET_ADDRESS, CITY, STATE AS STATE_CODE, LEFT(LPAD(ZIP_CODE, 5, '0'), 5) AS ZIP5,
       NAICS_CODE, INDUSTRY_DESCRIPTION,
       TRY_TO_NUMBER(ANNUAL_AVERAGE_EMPLOYEES) AS ANNUAL_AVG_EMPLOYEES,
       TRY_TO_NUMBER(TOTAL_HOURS_WORKED)       AS TOTAL_HOURS_WORKED,
       TRY_TO_NUMBER(TOTAL_DEATHS)             AS TOTAL_DEATHS,
       TRY_TO_NUMBER(TOTAL_DAFW_CASES)         AS DAFW_CASES,
       TRY_TO_NUMBER(TOTAL_DJTR_CASES)         AS DJTR_CASES,
       TRY_TO_NUMBER(TOTAL_OTHER_CASES)        AS OTHER_CASES,
       TRY_TO_NUMBER(TOTAL_DAFW_DAYS)          AS DAFW_DAYS,
       TRY_TO_NUMBER(YEAR_FILING_FOR)          AS FILING_YEAR,
       _SOURCE_FILE, _LOADED_AT
FROM (SELECT * FROM DOL_FRAUD_DEMO.RAW_PUBLIC.ITA_300A_2024
      UNION ALL BY NAME
      SELECT * FROM DOL_FRAUD_DEMO.RAW_PUBLIC.ITA_300A_2025);

