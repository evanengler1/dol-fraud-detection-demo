CREATE OR REPLACE VIEW OSHA_VIOLATION COMMENT = 'Public: OSHA citations 2016+ (DOL_OSHA_DEMO)' AS
SELECT ACTIVITY_NR, CITATION_ID, STANDARD, VIOL_TYPE, ISSUANCE_DATE::DATE AS ISSUANCE_DATE,
       ABATE_DATE::DATE AS ABATE_DATE, INITIAL_PENALTY, CURRENT_PENALTY, PENALTY_REDUCTION,
