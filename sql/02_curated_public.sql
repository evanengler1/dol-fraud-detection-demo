-- BLS QCEW 2024: private-sector state x NAICS wage benchmarks --------------------
-- agglvl 50-58 = state-level ownership x NAICS sector..6-digit; own_code 5 = private
CREATE OR REPLACE TABLE QCEW_STATE_INDUSTRY_2024 COMMENT = 'Public: BLS QCEW 2024 annual averages, private sector, by state and NAICS (data.bls.gov)' AS
SELECT s.STATE_CODE, q.AREA_FIPS, q.INDUSTRY_CODE AS NAICS_CODE,
       TRY_TO_NUMBER(q.AGGLVL_CODE) AS AGGLVL_CODE,
       LENGTH(REGEXP_REPLACE(q.INDUSTRY_CODE, '[^0-9]', '')) AS NAICS_DIGITS,
       TRY_TO_NUMBER(q.ANNUAL_AVG_ESTABS)    AS ESTABLISHMENTS,
       TRY_TO_NUMBER(q.ANNUAL_AVG_EMPLVL)    AS EMPLOYMENT,
       TRY_TO_NUMBER(q.TOTAL_ANNUAL_WAGES)   AS TOTAL_WAGES,
       TRY_TO_NUMBER(q.ANNUAL_AVG_WKLY_WAGE) AS AVG_WEEKLY_WAGE,
       TRY_TO_NUMBER(q.AVG_ANNUAL_PAY)       AS AVG_ANNUAL_PAY,
       q._SOURCE_FILE, q._LOADED_AT
FROM DOL_FRAUD_DEMO.RAW_PUBLIC.QCEW_2024_ANNUAL q
JOIN STATE_REF s ON s.STATE_FIPS = LEFT(q.AREA_FIPS, 2)
WHERE q.OWN_CODE = '5'
  AND RIGHT(q.AREA_FIPS, 3) = '000'
  AND TRY_TO_NUMBER(q.AGGLVL_CODE) BETWEEN 54 AND 58
  AND q.DISCLOSURE_CODE IS NULL;

-- Existing DOL databases (used in place) -------------------------------------------
