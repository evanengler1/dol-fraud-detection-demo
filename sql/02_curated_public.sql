-- ETA 539: weekly claims by state -------------------------------------------------
CREATE OR REPLACE TABLE ETA_539_WEEKLY_CLAIMS COMMENT = 'Public: ETA 539 weekly UI claims by state (oui.doleta.gov ar539.csv)' AS
SELECT ST                                         AS STATE_CODE,
       TRY_TO_DATE(RPTDATE)                       AS WEEK_ENDING,
       TRY_TO_DATE(C2)                            AS REFLECTED_WEEK_ENDING,
       TRY_TO_NUMBER(C3)                          AS INITIAL_CLAIMS,          -- IC (state UI)
       TRY_TO_NUMBER(C4)                          AS INITIAL_CLAIMS_UCFE,     -- FIC
       TRY_TO_NUMBER(C5)                          AS INITIAL_CLAIMS_UCX,      -- XIC
       TRY_TO_NUMBER(C8)                          AS CONTINUED_WEEKS,         -- CW
       TRY_TO_NUMBER(C18)                         AS COVERED_EMPLOYMENT,      -- CE
       TRY_TO_DECIMAL(C19, 10, 4)                 AS INSURED_UNEMP_RATE,      -- R (IUR %)
       C22                                        AS EB_STATUS,
       _SOURCE_FILE, _LOADED_AT
FROM DOL_FRAUD_DEMO.RAW_PUBLIC.ETA_539;

