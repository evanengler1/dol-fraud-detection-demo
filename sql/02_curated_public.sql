-- OSHA accident abstracts: concatenate narrative lines per accident ---------------
CREATE OR REPLACE TABLE OSHA_ACCIDENT_NARRATIVE COMMENT = 'Public: OSHA accident investigation abstracts (data.dol.gov OSHA/accident_abstract), one row per accident' AS
SELECT TRY_TO_NUMBER(SUMMARY_NR) AS SUMMARY_NR,
       LISTAGG(ABSTRACT_TEXT, ' ') WITHIN GROUP (ORDER BY TRY_TO_NUMBER(LINE_NR)) AS ABSTRACT_TEXT,
       MAX(_SOURCE_FILE) AS _SOURCE_FILE, MAX(_LOADED_AT) AS _LOADED_AT
FROM DOL_FRAUD_DEMO.RAW_PUBLIC.OSHA_ACCIDENT_ABSTRACT
WHERE ABSTRACT_TEXT IS NOT NULL
GROUP BY 1;

