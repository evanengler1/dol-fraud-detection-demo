-- =============================================================================
-- DOL Fraud Detection Demo - 04 Employer entity resolution
-- DOL publishes no shared employer key. This builds one across five sources:
--   EIN-bearing:  OSHA ITA 300A, EBSA Form 5500, OFLC H-2A/H-2B
--   Name-only:    WHD enforcement cases, OSHA inspections
-- Method
--   1. Standardize names (upper, strip punctuation and legal suffixes) and addresses
--   2. Deterministic: EIN clusters; then exact name + ZIP5 to an EIN cluster
--   3. Fuzzy: block on state + ZIP5 + name prefix, Jaro-Winkler >= 95 plus an
--      address check auto-accepts; 88-94 goes to the review queue
--      (prior WHD demo: JW >= 92 alone over-merged distinct employers)
--   4. Unmatched name-only records cluster on name + ZIP5
-- Output: CURATED.EMPLOYER_SOURCE_RECORD, EMPLOYER_XREF, EMPLOYER_MASTER,
--         EMPLOYER_MATCH_REVIEW. Real names stay in CANONICAL_NAME (masked in 11);
--         every screen shows DISPLAY_ID ("Employer #48213").
-- =============================================================================

USE ROLE DOL_FRAUD_DEMO_ROLE;
USE WAREHOUSE DOL_FRAUD_WH;
USE SCHEMA DOL_FRAUD_DEMO.CURATED;

-- Name / address standardization -------------------------------------------------
CREATE OR REPLACE FUNCTION NORM_NAME(N VARCHAR)
  RETURNS VARCHAR
  COMMENT = 'Uppercase, strip punctuation, legal suffixes and DBA tails, collapse spaces'
AS $$
  NULLIF(TRIM(REGEXP_REPLACE(
    REGEXP_REPLACE(
      REGEXP_REPLACE(
        REGEXP_REPLACE(UPPER(SPLIT_PART(SPLIT_PART(N, ' DBA ', 1), ' D/B/A ', 1)), '&', ' AND '),
        '[^A-Z0-9 ]', ' '),
      '\\b(LLC|L L C|INC|INCORPORATED|CORP|CORPORATION|CO|COMPANY|LTD|LIMITED|LP|LLP|PLLC|PC|PA|THE)\\b', ' '),
    ' +', ' ')), '')
$$;

CREATE OR REPLACE FUNCTION NORM_ADDR(A VARCHAR)
  RETURNS VARCHAR
  COMMENT = 'Uppercase street address with common suffixes abbreviated'
AS $$
  NULLIF(TRIM(REGEXP_REPLACE(
    REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(REGEXP_REPLACE(
      REGEXP_REPLACE(UPPER(A), '[^A-Z0-9 ]', ' '),
      '\\bSTREET\\b', 'ST'), '\\bAVENUE\\b', 'AVE'), '\\bROAD\\b', 'RD'),
      '\\bBOULEVARD\\b', 'BLVD'), '\\b(SUITE|STE|UNIT|APT|BLDG)\\b.*$', ''),
    ' +', ' ')), '')
$$;

-- 1. Unified source records -------------------------------------------------------
CREATE OR REPLACE TABLE EMPLOYER_SOURCE_RECORD (
  SOURCE_SYSTEM  VARCHAR,          -- ITA | FORM5500 | OFLC | WHD | OSHA
  SOURCE_KEY     VARCHAR,
  RAW_NAME       VARCHAR,
  NORM_NAME      VARCHAR,
  EIN            VARCHAR(9),
  STREET_ADDRESS VARCHAR,
  NORM_ADDRESS   VARCHAR,
  CITY           VARCHAR,
  STATE_CODE     VARCHAR(2),
  ZIP5           VARCHAR(5),
  NAICS_CODE     VARCHAR
) COMMENT = 'Public: employer-bearing records from ITA, Form 5500, OFLC, WHD and OSHA, standardized';

INSERT INTO EMPLOYER_SOURCE_RECORD
SELECT 'ITA', TO_VARCHAR(ITA_ID), COALESCE(COMPANY_NAME, ESTABLISHMENT_NAME),
       NORM_NAME(COALESCE(COMPANY_NAME, ESTABLISHMENT_NAME)), EIN,
       STREET_ADDRESS, NORM_ADDR(STREET_ADDRESS), UPPER(CITY), STATE_CODE, ZIP5, NAICS_CODE
FROM ITA_300A
UNION ALL
SELECT 'FORM5500', ACK_ID, SPONSOR_NAME, NORM_NAME(SPONSOR_NAME), EIN,
       STREET_ADDRESS, NORM_ADDR(STREET_ADDRESS), UPPER(CITY), STATE_CODE, ZIP5, NAICS_CODE
FROM FORM_5500
UNION ALL
SELECT 'OFLC', CASE_NUMBER, EMPLOYER_NAME, NORM_NAME(EMPLOYER_NAME), EIN,
       STREET_ADDRESS, NORM_ADDR(STREET_ADDRESS), UPPER(CITY), STATE_CODE, ZIP5, NAICS_CODE
FROM OFLC_H2_CASES
UNION ALL
SELECT 'WHD', TO_VARCHAR(CASE_ID), LEGAL_NAME, NORM_NAME(COALESCE(LEGAL_NAME, TRADE_NAME)), NULL,
       STREET_ADDRESS, NORM_ADDR(STREET_ADDRESS), UPPER(CITY), STATE_CODE, ZIP5, NAICS_CODE
FROM WHD_CASE
UNION ALL
SELECT 'OSHA', TO_VARCHAR(ACTIVITY_NR), ESTAB_NAME, NORM_NAME(ESTAB_NAME), NULL,
       SITE_ADDRESS, NORM_ADDR(SITE_ADDRESS), UPPER(SITE_CITY), STATE_CODE, ZIP5, NAICS_CODE
FROM OSHA_INSPECTION;

DELETE FROM EMPLOYER_SOURCE_RECORD WHERE NORM_NAME IS NULL AND EIN IS NULL;

-- 2a. EIN clusters: one employer per EIN ------------------------------------------
CREATE OR REPLACE TEMPORARY TABLE EIN_CLUSTER AS
SELECT EIN, 'E' || EIN AS EMPLOYER_ID,
       MODE(NORM_NAME)  AS NORM_NAME,
       MODE(STATE_CODE) AS STATE_CODE
FROM EMPLOYER_SOURCE_RECORD WHERE EIN IS NOT NULL GROUP BY 1;

-- (name, ZIP5) -> EIN lookup, keeping only unambiguous keys
CREATE OR REPLACE TEMPORARY TABLE NAME_ZIP_TO_EIN AS
SELECT NORM_NAME, ZIP5, MIN(EIN) AS EIN
FROM EMPLOYER_SOURCE_RECORD
WHERE EIN IS NOT NULL AND NORM_NAME IS NOT NULL AND ZIP5 IS NOT NULL
GROUP BY 1, 2 HAVING COUNT(DISTINCT EIN) = 1;

-- (name, state) -> EIN lookup, unambiguous only
CREATE OR REPLACE TEMPORARY TABLE NAME_STATE_TO_EIN AS
SELECT NORM_NAME, STATE_CODE, MIN(EIN) AS EIN
FROM EMPLOYER_SOURCE_RECORD
WHERE EIN IS NOT NULL AND NORM_NAME IS NOT NULL AND LENGTH(NORM_NAME) >= 6
GROUP BY 1, 2 HAVING COUNT(DISTINCT EIN) = 1;

-- 2b. Cross-reference: EIN records, then exact name matches -----------------------
CREATE OR REPLACE TABLE EMPLOYER_XREF (
  SOURCE_SYSTEM VARCHAR, SOURCE_KEY VARCHAR, EMPLOYER_ID VARCHAR,
  MATCH_METHOD VARCHAR, MATCH_CONFIDENCE NUMBER(5, 2)
) COMMENT = 'Public: source record to resolved employer, with match method and confidence';

INSERT INTO EMPLOYER_XREF
SELECT SOURCE_SYSTEM, SOURCE_KEY, 'E' || EIN, 'EIN', 1.00
FROM EMPLOYER_SOURCE_RECORD WHERE EIN IS NOT NULL;

INSERT INTO EMPLOYER_XREF
SELECT r.SOURCE_SYSTEM, r.SOURCE_KEY, 'E' || z.EIN, 'NAME_ZIP_EXACT', 0.97
FROM EMPLOYER_SOURCE_RECORD r
JOIN NAME_ZIP_TO_EIN z ON z.NORM_NAME = r.NORM_NAME AND z.ZIP5 = r.ZIP5
WHERE r.EIN IS NULL;

INSERT INTO EMPLOYER_XREF
SELECT r.SOURCE_SYSTEM, r.SOURCE_KEY, 'E' || s.EIN, 'NAME_STATE_EXACT', 0.90
FROM EMPLOYER_SOURCE_RECORD r
JOIN NAME_STATE_TO_EIN s ON s.NORM_NAME = r.NORM_NAME AND s.STATE_CODE = r.STATE_CODE
WHERE r.EIN IS NULL
  AND NOT EXISTS (SELECT 1 FROM EMPLOYER_XREF x WHERE x.SOURCE_SYSTEM = r.SOURCE_SYSTEM AND x.SOURCE_KEY = r.SOURCE_KEY);

-- 3. Fuzzy matching for the remaining name-only records --------------------------
-- Candidate EIN-cluster representatives per (state, ZIP5, name prefix)
CREATE OR REPLACE TEMPORARY TABLE EIN_REP AS
SELECT DISTINCT EIN, NORM_NAME, NORM_ADDRESS, STATE_CODE, ZIP5, LEFT(NORM_NAME, 3) AS NAME_BLOCK
FROM EMPLOYER_SOURCE_RECORD
WHERE EIN IS NOT NULL AND NORM_NAME IS NOT NULL AND ZIP5 IS NOT NULL;

CREATE OR REPLACE TEMPORARY TABLE FUZZY_CANDIDATES AS
SELECT r.SOURCE_SYSTEM, r.SOURCE_KEY, r.NORM_NAME AS SRC_NAME, r.NORM_ADDRESS AS SRC_ADDR,
       e.EIN, e.NORM_NAME AS EIN_NAME, e.NORM_ADDRESS AS EIN_ADDR,
       JAROWINKLER_SIMILARITY(r.NORM_NAME, e.NORM_NAME) AS NAME_SIM,
       JAROWINKLER_SIMILARITY(COALESCE(r.NORM_ADDRESS, ''), COALESCE(e.NORM_ADDRESS, '')) AS ADDR_SIM
FROM EMPLOYER_SOURCE_RECORD r
JOIN EIN_REP e
  ON e.STATE_CODE = r.STATE_CODE AND e.ZIP5 = r.ZIP5 AND e.NAME_BLOCK = LEFT(r.NORM_NAME, 3)
WHERE r.EIN IS NULL AND r.NORM_NAME IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM EMPLOYER_XREF x WHERE x.SOURCE_SYSTEM = r.SOURCE_SYSTEM AND x.SOURCE_KEY = r.SOURCE_KEY)
  AND JAROWINKLER_SIMILARITY(r.NORM_NAME, e.NORM_NAME) >= 88
QUALIFY ROW_NUMBER() OVER (PARTITION BY r.SOURCE_SYSTEM, r.SOURCE_KEY
                           ORDER BY NAME_SIM DESC, ADDR_SIM DESC) = 1;

-- Auto-accept: very similar name AND matching address
INSERT INTO EMPLOYER_XREF
SELECT SOURCE_SYSTEM, SOURCE_KEY, 'E' || EIN, 'FUZZY_NAME_ADDR',
       ROUND((NAME_SIM * 0.7 + ADDR_SIM * 0.3) / 100, 2)
FROM FUZZY_CANDIDATES
WHERE NAME_SIM >= 95 AND ADDR_SIM >= 90;

-- Review queue: plausible but not certain
CREATE OR REPLACE TABLE EMPLOYER_MATCH_REVIEW
  COMMENT = 'Public: fuzzy employer matches needing analyst review (name similarity 88-94 or address mismatch)' AS
SELECT SOURCE_SYSTEM, SOURCE_KEY, SRC_NAME, SRC_ADDR, 'E' || EIN AS CANDIDATE_EMPLOYER_ID,
       EIN_NAME, EIN_ADDR, NAME_SIM, ADDR_SIM, 'PENDING' AS REVIEW_STATUS
FROM FUZZY_CANDIDATES
WHERE NOT (NAME_SIM >= 95 AND ADDR_SIM >= 90);

-- 4. Remaining name-only records cluster on (name, ZIP5) -------------------------
INSERT INTO EMPLOYER_XREF
SELECT r.SOURCE_SYSTEM, r.SOURCE_KEY,
       'N' || LEFT(SHA2(r.NORM_NAME || '|' || COALESCE(r.ZIP5, r.STATE_CODE, '')), 12),
       'NAME_ZIP_CLUSTER', 0.80
FROM EMPLOYER_SOURCE_RECORD r
WHERE r.EIN IS NULL AND r.NORM_NAME IS NOT NULL
  AND NOT EXISTS (SELECT 1 FROM EMPLOYER_XREF x WHERE x.SOURCE_SYSTEM = r.SOURCE_SYSTEM AND x.SOURCE_KEY = r.SOURCE_KEY);

-- 5. Employer master ------------------------------------------------------------------
-- Explicit DDL: synthetic employers (incl. the hero) are inserted later in 05
CREATE OR REPLACE TABLE EMPLOYER_MASTER (
  EMPLOYER_ID        VARCHAR,
  DISPLAY_ID         VARCHAR,       -- pseudonym shown on screen, e.g. "Employer #48213"
  CANONICAL_NAME     VARCHAR,       -- real name; masked for every demo role (11_governance)
  EIN                VARCHAR(9),
  STATE_CODE         VARCHAR(2),
  CITY               VARCHAR,
  ZIP5               VARCHAR(5),
  NAICS_CODE         VARCHAR,
  NAICS4             VARCHAR(4),
  IN_ITA             BOOLEAN,
  IN_FORM5500        BOOLEAN,
  IN_OFLC            BOOLEAN,
  IN_WHD             BOOLEAN,
  IN_OSHA            BOOLEAN,
  SOURCE_COUNT       NUMBER,
  AGENCY_COUNT       NUMBER,        -- WHD, OSHA (incl. ITA), OFLC (ETA)
  SOURCE_RECORDS     NUMBER,
  MIN_MATCH_CONF     NUMBER(5, 2),
  IS_SYNTHETIC       BOOLEAN,
  DATA_ORIGIN        VARCHAR
) COMMENT = 'Resolved employers across WHD, OSHA, ITA, OFLC and Form 5500. Public data plus flagged synthetic employers.';

INSERT INTO EMPLOYER_MASTER
WITH j AS (
  SELECT x.EMPLOYER_ID, x.MATCH_CONFIDENCE, r.*
  FROM EMPLOYER_XREF x
  JOIN EMPLOYER_SOURCE_RECORD r ON r.SOURCE_SYSTEM = x.SOURCE_SYSTEM AND r.SOURCE_KEY = x.SOURCE_KEY),
agg AS (
  SELECT EMPLOYER_ID,
         MODE(RAW_NAME) AS CANONICAL_NAME, MAX(EIN) AS EIN,
         MODE(STATE_CODE) AS STATE_CODE, MODE(CITY) AS CITY, MODE(ZIP5) AS ZIP5,
         MODE(NAICS_CODE) AS NAICS_CODE,
         BOOLOR_AGG(SOURCE_SYSTEM = 'ITA')      AS IN_ITA,
         BOOLOR_AGG(SOURCE_SYSTEM = 'FORM5500') AS IN_FORM5500,
         BOOLOR_AGG(SOURCE_SYSTEM = 'OFLC')     AS IN_OFLC,
         BOOLOR_AGG(SOURCE_SYSTEM = 'WHD')      AS IN_WHD,
         BOOLOR_AGG(SOURCE_SYSTEM = 'OSHA')     AS IN_OSHA,
         COUNT(DISTINCT SOURCE_SYSTEM) AS SOURCE_COUNT,
         COUNT(*) AS SOURCE_RECORDS, MIN(MATCH_CONFIDENCE) AS MIN_MATCH_CONF
  FROM j GROUP BY 1)
SELECT EMPLOYER_ID,
       'Employer #' || LPAD(TO_VARCHAR(ROW_NUMBER() OVER (ORDER BY HASH(EMPLOYER_ID))), 6, '0'),
       CANONICAL_NAME, EIN, STATE_CODE, CITY, ZIP5, NAICS_CODE, LEFT(NAICS_CODE, 4),
       IN_ITA, IN_FORM5500, IN_OFLC, IN_WHD, IN_OSHA, SOURCE_COUNT,
       IFF(IN_WHD, 1, 0) + IFF(IN_OSHA OR IN_ITA, 1, 0) + IFF(IN_OFLC, 1, 0),
       SOURCE_RECORDS, MIN_MATCH_CONF, FALSE, 'PUBLIC'
FROM agg;

-- Match statistics (for the Entity Resolution app page) ---------------------------
CREATE OR REPLACE VIEW EMPLOYER_MATCH_STATS COMMENT = 'Entity resolution match rates by source and method' AS
SELECT x.SOURCE_SYSTEM, x.MATCH_METHOD, COUNT(*) AS RECORDS,
       ROUND(RATIO_TO_REPORT(COUNT(*)) OVER (PARTITION BY x.SOURCE_SYSTEM) * 100, 1) AS PCT_OF_SOURCE
FROM EMPLOYER_XREF x GROUP BY 1, 2;

-- Quick summary
SELECT 'source records' AS metric, COUNT(*) AS value FROM EMPLOYER_SOURCE_RECORD
UNION ALL SELECT 'resolved employers', COUNT(*) FROM EMPLOYER_MASTER
UNION ALL SELECT 'employers in 2+ agencies', COUNT_IF(AGENCY_COUNT >= 2) FROM EMPLOYER_MASTER
UNION ALL SELECT 'employers in all 3 agencies', COUNT_IF(AGENCY_COUNT = 3) FROM EMPLOYER_MASTER
UNION ALL SELECT 'review queue', COUNT(*) FROM EMPLOYER_MATCH_REVIEW;

SELECT * FROM EMPLOYER_MATCH_STATS ORDER BY SOURCE_SYSTEM, RECORDS DESC;
