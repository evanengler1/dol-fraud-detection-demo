-- =============================================================================
-- DOL Fraud Detection Demo - 06 Curated analytics: Dynamic Tables + employer risk
-- Claims pipeline (synthetic) and the state baseline (public) are Dynamic
-- Tables on tables this demo owns. Employer risk reads the existing
-- DOL_WHD_DEMO / DOL_OSHA_DEMO tables in place; those tables belong to other
-- demo roles and do not have change tracking, so employer risk is rebuilt by a
-- procedure on a weekly task (OSHA/WHD publish weekly) instead of a DT.
-- Rule flags here are deterministic and kept separate from ML scores (07).
-- =============================================================================

USE ROLE DOL_FRAUD_DEMO_ROLE;
USE WAREHOUSE DOL_FRAUD_WH;
USE SCHEMA DOL_FRAUD_DEMO.ANALYTICS;

-- =============================================================================
-- A. Public: state UI baseline (ETA 539 + 227 + 5159 + BAM), quarterly
-- =============================================================================
CREATE OR REPLACE DYNAMIC TABLE DT_STATE_UI_BASELINE
  TARGET_LAG = '1 day'
  WAREHOUSE = DOL_FRAUD_WH
  COMMENT = 'Public: quarterly UI claims, benefits paid, fraud overpayments, recovery and BAM fraud rate by state'
AS
WITH claims AS (
  SELECT STATE_CODE, LAST_DAY(WEEK_ENDING, 'quarter') AS QUARTER_ENDING,
         SUM(INITIAL_CLAIMS) AS INITIAL_CLAIMS, SUM(CONTINUED_WEEKS) AS CONTINUED_WEEKS,
         MAX(COVERED_EMPLOYMENT) AS COVERED_EMPLOYMENT
  FROM DOL_FRAUD_DEMO.CURATED.ETA_539_WEEKLY_CLAIMS
  WHERE WEEK_ENDING >= '2015-01-01'
  GROUP BY 1, 2),
paid AS (
  SELECT STATE_CODE, LAST_DAY(MONTH_ENDING, 'quarter') AS QUARTER_ENDING,
         SUM(BENEFITS_PAID) AS BENEFITS_PAID, SUM(FIRST_PAYMENTS) AS FIRST_PAYMENTS
  FROM DOL_FRAUD_DEMO.CURATED.ETA_5159_PAYMENTS
  WHERE MONTH_ENDING >= '2015-01-01'
  GROUP BY 1, 2),
op AS (
  SELECT STATE_CODE, QUARTER_ENDING, FRAUD_CASES, FRAUD_DOLLARS, SCHEME_DOLLARS, NONFRAUD_DOLLARS,
         FRAUD_RECOVERED, REFERRED_FOR_PROSECUTION, CONVICTIONS,
         DET_WAGE_CROSSMATCH_DOLLARS + DET_NDNH_DOLLARS + DET_SDNH_DOLLARS + DET_IB_CROSSMATCH_DOLLARS AS CROSSMATCH_DETECTED_DOLLARS
  FROM DOL_FRAUD_DEMO.CURATED.ETA_227_OVERPAYMENTS
  WHERE QUARTER_ENDING >= '2015-01-01'),
bam AS (
  SELECT STATE_CODE, LAST_DAY(DATE_FROM_PARTS(YEAR, QUARTER * 3, 1)) AS QUARTER_ENDING,
         FRAUD_RATE AS BAM_FRAUD_RATE, OVERPAYMENT_RATE AS BAM_OVERPAYMENT_RATE
  FROM DOL_FRAUD_DEMO.CURATED.BAM_INTEGRITY_RATES)
SELECT c.STATE_CODE, s.STATE_NAME, c.QUARTER_ENDING,
       c.INITIAL_CLAIMS, c.CONTINUED_WEEKS, c.COVERED_EMPLOYMENT,
       p.BENEFITS_PAID, p.FIRST_PAYMENTS,
       o.FRAUD_CASES, o.FRAUD_DOLLARS, o.SCHEME_DOLLARS, o.NONFRAUD_DOLLARS, o.FRAUD_RECOVERED,
       o.CROSSMATCH_DETECTED_DOLLARS, o.REFERRED_FOR_PROSECUTION, o.CONVICTIONS,
       DIV0NULL(o.FRAUD_DOLLARS, p.BENEFITS_PAID)      AS FRAUD_PCT_OF_PAID,
       DIV0NULL(o.FRAUD_RECOVERED, o.FRAUD_DOLLARS)    AS FRAUD_RECOVERY_RATIO,
       b.BAM_FRAUD_RATE, b.BAM_OVERPAYMENT_RATE,
       'PUBLIC' AS DATA_ORIGIN
FROM claims c
JOIN DOL_FRAUD_DEMO.CURATED.STATE_REF s ON s.STATE_CODE = c.STATE_CODE
LEFT JOIN paid p ON p.STATE_CODE = c.STATE_CODE AND p.QUARTER_ENDING = c.QUARTER_ENDING
LEFT JOIN op   o ON o.STATE_CODE = c.STATE_CODE AND o.QUARTER_ENDING = c.QUARTER_ENDING
LEFT JOIN bam  b ON b.STATE_CODE = c.STATE_CODE AND b.QUARTER_ENDING = c.QUARTER_ENDING;

-- =============================================================================
-- B. Synthetic claims pipeline (current-year claims)
-- =============================================================================
-- B1. Link graph: claims that share a bank account, device, IP, phone or email
CREATE OR REPLACE DYNAMIC TABLE DT_CLAIM_LINKS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = DOL_FRAUD_WH
  COMMENT = 'Synthetic data. Edges between current claims sharing a bank account, device, IP address, phone or email.'
AS
WITH attr AS (
  SELECT CLAIM_ID, 'BANK_ACCOUNT' AS LINK_TYPE, BANK_ROUTING || ':' || BANK_ACCOUNT AS LINK_VALUE FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, 'DEVICE', DEVICE_ID   FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, 'IP',     IP_ADDRESS  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, 'PHONE',  CLAIM_PHONE FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, 'EMAIL',  CLAIM_EMAIL FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR')
SELECT a.CLAIM_ID AS CLAIM_ID_A, b.CLAIM_ID AS CLAIM_ID_B, a.LINK_TYPE, a.LINK_VALUE
FROM attr a
JOIN attr b ON b.LINK_TYPE = a.LINK_TYPE AND b.LINK_VALUE = a.LINK_VALUE AND b.CLAIM_ID > a.CLAIM_ID
WHERE a.LINK_VALUE IS NOT NULL;

-- B2. Shared-attribute clusters (rings, farms) with dollars and state spread
CREATE OR REPLACE DYNAMIC TABLE DT_CLAIM_RING_STATS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = DOL_FRAUD_WH
  COMMENT = 'Synthetic data. Clusters of 3+ current claims sharing one bank account, device, IP, phone or email.'
AS
WITH attr AS (
  SELECT CLAIM_ID, STATE_CODE, WEEKLY_BENEFIT_AMT * WEEKS_PAID AS PAID, FILED_TS,
         'BANK_ACCOUNT' AS LINK_TYPE, BANK_ROUTING || ':' || BANK_ACCOUNT AS LINK_VALUE
  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, STATE_CODE, WEEKLY_BENEFIT_AMT * WEEKS_PAID, FILED_TS, 'DEVICE', DEVICE_ID
  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, STATE_CODE, WEEKLY_BENEFIT_AMT * WEEKS_PAID, FILED_TS, 'IP', IP_ADDRESS
  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR'
  UNION ALL SELECT CLAIM_ID, STATE_CODE, WEEKLY_BENEFIT_AMT * WEEKS_PAID, FILED_TS, 'PHONE', CLAIM_PHONE
  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM WHERE CLAIM_WINDOW = 'CUR')
SELECT LINK_TYPE, LINK_VALUE,
       COUNT(DISTINCT CLAIM_ID) AS CLAIM_COUNT,
       COUNT(DISTINCT STATE_CODE) AS STATE_COUNT,
       ARRAY_AGG(DISTINCT STATE_CODE) AS STATES,
       SUM(PAID) AS TOTAL_PAID,
       MIN(FILED_TS) AS FIRST_FILED, MAX(FILED_TS) AS LAST_FILED,
       DATEDIFF(hour, MIN(FILED_TS), MAX(FILED_TS)) AS FILING_SPAN_HOURS,
       'SYNTHETIC' AS DATA_ORIGIN
FROM attr
WHERE LINK_VALUE IS NOT NULL
GROUP BY 1, 2
HAVING COUNT(DISTINCT CLAIM_ID) >= 3;

-- B3. Claim features (cross-matches, identity, employer, network)
CREATE OR REPLACE DYNAMIC TABLE DT_CLAIM_FEATURES
  TARGET_LAG = '5 minutes'
  WAREHOUSE = DOL_FRAUD_WH
  COMMENT = 'Synthetic data. One row per current claim with cross-match, identity, employer and network features.'
AS
WITH cur AS (
  SELECT c.*, t.SSN, t.DOB, t.EMAIL AS IDENTITY_EMAIL, t.PHONE_IS_VOIP, t.ADDRESS_IS_CMRA,
         t.IDENTITY_VERIFIED, t.ACCOUNT_CREATED_TS, t.PRIMARY_LANGUAGE
  FROM DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM c
  JOIN DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIMANT t ON t.CLAIMANT_ID = c.CLAIMANT_ID
  WHERE c.CLAIM_WINDOW = 'CUR'),
bank AS (SELECT BANK_ROUTING, BANK_ACCOUNT, COUNT(*) AS N FROM cur GROUP BY 1, 2),
dev  AS (SELECT DEVICE_ID, COUNT(*) AS N, COUNT(DISTINCT STATE_CODE) AS S FROM cur GROUP BY 1),
ip   AS (SELECT IP_ADDRESS, COUNT(*) AS N FROM cur GROUP BY 1),
ssn  AS (SELECT SSN, COUNT(DISTINCT STATE_CODE) AS S FROM cur GROUP BY 1),
nh AS (
  SELECT c.CLAIM_ID, COUNT(*) AS N, MIN(n.HIRE_DATE) AS FIRST_HIRE
  FROM cur c JOIN DOL_FRAUD_DEMO.RAW_SYNTH.NEW_HIRE n
    ON n.SSN = c.SSN AND n.HIRE_DATE BETWEEN c.FILED_TS::DATE AND DATEADD(week, c.WEEKS_PAID, c.FILED_TS)::DATE
  GROUP BY 1),
wq AS (
  SELECT c.CLAIM_ID,
         COUNT_IF(w.QTR_START < DATE_TRUNC(quarter, c.SEPARATION_DATE)) AS BASE_QTRS,
         COUNT_IF(w.QTR_START >= DATE_TRUNC(quarter, c.FILED_TS::DATE)) AS WAGE_QTRS_DURING_CLAIM,
         COUNT_IF(w.QTR_START < DATE_TRUNC(quarter, c.SEPARATION_DATE) AND MOD(w.WAGES, 1000) = 0) AS ROUND_WAGE_QTRS
  FROM cur c LEFT JOIN DOL_FRAUD_DEMO.RAW_SYNTH.WAGE_RECORD w ON w.SSN = c.SSN
  GROUP BY 1),
emp AS (
  SELECT m.EMPLOYER_ID, m.IS_SYNTHETIC,
         (m.IN_ITA OR m.IN_FORM5500 OR m.IN_OSHA OR m.IN_WHD OR m.IN_OFLC) AS HAS_PUBLIC_FOOTPRINT,
         s.REGISTERED_DATE
  FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_MASTER m
  LEFT JOIN DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_EMPLOYER s ON s.EMPLOYER_ID = m.EMPLOYER_ID),
burst AS (
  SELECT LAST_EMPLOYER_ID, COUNT(*) AS SEPARATIONS_30D
  FROM cur GROUP BY LAST_EMPLOYER_ID, DATE_TRUNC(month, SEPARATION_DATE)),
burst_max AS (SELECT LAST_EMPLOYER_ID, MAX(SEPARATIONS_30D) AS MAX_MONTHLY_SEPARATIONS FROM burst GROUP BY 1)
SELECT c.CLAIM_ID, c.CLAIMANT_ID, c.STATE_CODE, c.LAST_EMPLOYER_ID, c.FILED_TS, c.STATUS,
       c.WEEKLY_BENEFIT_AMT, c.WEEKS_PAID, c.WEEKLY_BENEFIT_AMT * c.WEEKS_PAID AS AMOUNT_PAID,
       c.FILING_CHANNEL,
       -- network
       b.N AS BANK_ACCOUNT_CLAIM_COUNT,
       d.N AS DEVICE_CLAIM_COUNT, d.S AS DEVICE_STATE_COUNT,
       i.N AS IP_CLAIM_COUNT,
       -- cross-matches
       s.S AS SSN_STATE_COUNT,
       COALESCE(nh.N, 0) AS NEW_HIRE_MATCHES,
       nh.FIRST_HIRE AS FIRST_NEW_HIRE_DATE,
       COALESCE(wq.WAGE_QTRS_DURING_CLAIM, 0) AS WAGE_QTRS_DURING_CLAIM,
       COALESCE(wq.BASE_QTRS, 0) AS BASE_PERIOD_WAGE_QTRS,
       COALESCE(wq.ROUND_WAGE_QTRS, 0) AS ROUND_WAGE_QTRS,
       -- identity
       DATEDIFF(hour, c.ACCOUNT_CREATED_TS, c.FILED_TS) AS ACCOUNT_AGE_HOURS,
       c.IDENTITY_VERIFIED, c.PHONE_IS_VOIP, c.ADDRESS_IS_CMRA,
       SPLIT_PART(c.CLAIM_EMAIL, '@', 2) NOT IN ('gmail.com', 'yahoo.com', 'outlook.com', 'icloud.com', 'aol.com', 'hotmail.com') AS EMAIL_UNCOMMON_DOMAIN,
       DATEDIFF(year, c.DOB, c.FILED_TS) AS CLAIMANT_AGE,
       -- employer
       COALESCE(e.IS_SYNTHETIC, FALSE) AS EMPLOYER_IS_SYNTHETIC,
       COALESCE(e.HAS_PUBLIC_FOOTPRINT, FALSE) AS EMPLOYER_HAS_PUBLIC_FOOTPRINT,
       DATEDIFF(day, e.REGISTERED_DATE, c.SEPARATION_DATE) AS EMPLOYER_AGE_AT_SEPARATION_DAYS,
       bm.MAX_MONTHLY_SEPARATIONS AS EMPLOYER_MAX_MONTHLY_SEPARATIONS,
       DIV0NULL(c.WEEKLY_BENEFIT_AMT, ds.MAX_WBA) AS WBA_PCT_OF_MAX,
       -- labels (seeded, for model training only)
       c.IS_FRAUD, c.FRAUD_PATTERN, c.FRAUD_GROUP,
       'SYNTHETIC' AS DATA_ORIGIN
FROM cur c
LEFT JOIN bank b ON b.BANK_ROUTING = c.BANK_ROUTING AND b.BANK_ACCOUNT = c.BANK_ACCOUNT
LEFT JOIN dev d ON d.DEVICE_ID = c.DEVICE_ID
LEFT JOIN ip i ON i.IP_ADDRESS = c.IP_ADDRESS
LEFT JOIN ssn s ON s.SSN = c.SSN
LEFT JOIN nh ON nh.CLAIM_ID = c.CLAIM_ID
LEFT JOIN wq ON wq.CLAIM_ID = c.CLAIM_ID
LEFT JOIN emp e ON e.EMPLOYER_ID = c.LAST_EMPLOYER_ID
LEFT JOIN burst_max bm ON bm.LAST_EMPLOYER_ID = c.LAST_EMPLOYER_ID
LEFT JOIN DOL_FRAUD_DEMO.RAW_SYNTH.DEMO_STATE ds ON ds.STATE_CODE = c.STATE_CODE;

-- B4. Deterministic rule flags (the rules engine), independent of ML
CREATE OR REPLACE DYNAMIC TABLE DT_CLAIM_RULE_FLAGS
  TARGET_LAG = '5 minutes'
  WAREHOUSE = DOL_FRAUD_WH
  COMMENT = 'Synthetic data. Rules-engine flags per claim. Risk indicators for demonstration only, not findings of fraud.'
AS
SELECT CLAIM_ID, CLAIMANT_ID, STATE_CODE, LAST_EMPLOYER_ID, FILED_TS, AMOUNT_PAID,
       BANK_ACCOUNT_CLAIM_COUNT >= 5                                         AS R1_SHARED_BANK_ACCOUNT,
       DEVICE_CLAIM_COUNT >= 10 OR IP_CLAIM_COUNT >= 10                      AS R2_DEVICE_OR_IP_FARM,
       SSN_STATE_COUNT >= 2                                                  AS R3_MULTI_STATE_SSN,
       NEW_HIRE_MATCHES > 0 OR WAGE_QTRS_DURING_CLAIM > 0                    AS R4_WORKING_WHILE_CLAIMING,
       EMPLOYER_IS_SYNTHETIC AND NOT EMPLOYER_HAS_PUBLIC_FOOTPRINT
         AND EMPLOYER_AGE_AT_SEPARATION_DAYS < 180
         AND EMPLOYER_MAX_MONTHLY_SEPARATIONS >= 10                          AS R5_FICTITIOUS_EMPLOYER,
       NOT IDENTITY_VERIFIED AND ACCOUNT_AGE_HOURS < 96
         AND (PHONE_IS_VOIP OR ADDRESS_IS_CMRA OR EMAIL_UNCOMMON_DOMAIN)
         AND BASE_PERIOD_WAGE_QTRS = 0                                       AS R6_SYNTHETIC_IDENTITY,
       ARRAY_COMPACT(ARRAY_CONSTRUCT(
         IFF(BANK_ACCOUNT_CLAIM_COUNT >= 5, 'Bank account shared by ' || BANK_ACCOUNT_CLAIM_COUNT || ' claims', NULL),
         IFF(DEVICE_CLAIM_COUNT >= 10, 'Device used for ' || DEVICE_CLAIM_COUNT || ' claims in ' || DEVICE_STATE_COUNT || ' states', NULL),
         IFF(IP_CLAIM_COUNT >= 10 AND DEVICE_CLAIM_COUNT < 10, 'IP address used for ' || IP_CLAIM_COUNT || ' claims', NULL),
         IFF(SSN_STATE_COUNT >= 2, 'Same SSN claiming in ' || SSN_STATE_COUNT || ' states', NULL),
         IFF(NEW_HIRE_MATCHES > 0, 'New-hire report during claim (' || TO_VARCHAR(FIRST_NEW_HIRE_DATE) || ')', NULL),
         IFF(WAGE_QTRS_DURING_CLAIM > 0 AND NEW_HIRE_MATCHES = 0, 'Wages reported during claim', NULL),
         IFF(EMPLOYER_IS_SYNTHETIC AND NOT EMPLOYER_HAS_PUBLIC_FOOTPRINT AND EMPLOYER_AGE_AT_SEPARATION_DAYS < 180,
             'Employer registered ' || EMPLOYER_AGE_AT_SEPARATION_DAYS || ' days before separation, no public footprint', NULL),
         IFF(NOT IDENTITY_VERIFIED AND ACCOUNT_AGE_HOURS < 96 AND BASE_PERIOD_WAGE_QTRS = 0,
             'Unverified identity, account ' || ACCOUNT_AGE_HOURS || 'h old, no wage history', NULL))) AS RULE_REASONS,
       'SYNTHETIC' AS DATA_ORIGIN
FROM DT_CLAIM_FEATURES;

-- =============================================================================
-- C. Employer risk across agencies (public data, rebuilt weekly)
-- =============================================================================
CREATE OR REPLACE PROCEDURE SP_REFRESH_EMPLOYER_RISK()
  RETURNS VARCHAR
  LANGUAGE SQL
  COMMENT = 'Rebuilds per-agency employer risk and the Risk 360 composite from public data plus fictional employers'
  EXECUTE AS CALLER
AS
$$
BEGIN
  -- WHD (P1 repeat violators, P2 back wages per employee vs NAICS peers, P3 H-2A findings)
  CREATE OR REPLACE TABLE DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_WHD_RISK
    COMMENT = 'Public: WHD enforcement signals per resolved employer (plus fictional hero/predecessor)' AS
  WITH cases AS (
    SELECT x.EMPLOYER_ID, w.CASE_ID, w.FINDINGS_END_DATE, w.TOTAL_BACK_WAGES, w.EMPLOYEES_OWED_BACK_WAGES,
           w.TOTAL_CMP_ASSESSED, w.IS_REPEAT_VIOLATOR, w.IS_WILLFUL_VIOLATOR, w.HAS_CHILD_LABOR,
           LEFT(w.NAICS_CODE, 4) AS NAICS4,
           EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.CURATED.WHD_CASE_PROGRAM p
                   WHERE p.CASE_ID = w.CASE_ID AND p.PROGRAM_LABEL ILIKE 'H-2A%' AND p.VIOLATION_COUNT > 0) AS HAS_H2A
    FROM DOL_FRAUD_DEMO.CURATED.WHD_CASE w
    JOIN DOL_FRAUD_DEMO.CURATED.EMPLOYER_XREF x ON x.SOURCE_SYSTEM = 'WHD' AND x.SOURCE_KEY = TO_VARCHAR(w.CASE_ID)
    UNION ALL
    SELECT EMPLOYER_ID, CASE_ID, FINDINGS_END_DATE, TOTAL_BACK_WAGES, EMPLOYEES_OWED_BACK_WAGES, TOTAL_CMP_ASSESSED,
           IS_REPEAT_VIOLATOR, IS_WILLFUL_VIOLATOR, FALSE, '5613', PROGRAM = 'H-2A'
    FROM DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_WHD_CASE),
emp AS (
    SELECT EMPLOYER_ID, MODE(NAICS4) AS NAICS4,
           COUNT(DISTINCT CASE_ID) AS WHD_CASES,
           COUNT(DISTINCT IFF(FINDINGS_END_DATE >= DATEADD(year, -5, CURRENT_DATE()), CASE_ID, NULL)) AS WHD_CASES_5YR,
           SUM(TOTAL_BACK_WAGES) AS BACK_WAGES, SUM(EMPLOYEES_OWED_BACK_WAGES) AS EMPLOYEES_OWED,
           SUM(TOTAL_CMP_ASSESSED) AS CMP_ASSESSED,
           BOOLOR_AGG(IS_REPEAT_VIOLATOR) AS ANY_REPEAT, BOOLOR_AGG(IS_WILLFUL_VIOLATOR) AS ANY_WILLFUL,
           BOOLOR_AGG(HAS_CHILD_LABOR) AS ANY_CHILD_LABOR, BOOLOR_AGG(HAS_H2A) AS ANY_H2A_VIOLATION,
           MAX(FINDINGS_END_DATE) AS LAST_FINDINGS_DATE
    FROM cases GROUP BY 1)
  SELECT e.*,
         DIV0NULL(BACK_WAGES, EMPLOYEES_OWED) AS BACK_WAGES_PER_EMPLOYEE,
         (DIV0NULL(BACK_WAGES, EMPLOYEES_OWED) - AVG(DIV0NULL(BACK_WAGES, EMPLOYEES_OWED)) OVER (PARTITION BY NAICS4))
           / NULLIF(STDDEV(DIV0NULL(BACK_WAGES, EMPLOYEES_OWED)) OVER (PARTITION BY NAICS4), 0) AS BW_PER_EE_Z,
         WHD_CASES_5YR >= 2 OR ANY_REPEAT AS P1_REPEAT_VIOLATOR,
         COALESCE((DIV0NULL(BACK_WAGES, EMPLOYEES_OWED) - AVG(DIV0NULL(BACK_WAGES, EMPLOYEES_OWED)) OVER (PARTITION BY NAICS4))
           / NULLIF(STDDEV(DIV0NULL(BACK_WAGES, EMPLOYEES_OWED)) OVER (PARTITION BY NAICS4), 0), 0) >= 2 AS P2_HIGH_BACK_WAGES,
         ANY_H2A_VIOLATION AS P3_H2A_VIOLATION
  FROM emp e;

  -- OSHA + ITA (P5 willful/repeat/FTA, P6 penalty reduction, P7 possible underreporting)
  CREATE OR REPLACE TABLE DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_OSHA_RISK
    COMMENT = 'Public: OSHA citation and ITA injury-rate signals per resolved employer (plus fictional hero)' AS
  WITH viol AS (
    SELECT x.EMPLOYER_ID, v.ACTIVITY_NR, v.VIOL_TYPE, v.INITIAL_PENALTY, v.CURRENT_PENALTY,
           v.FTA_INSP_NR IS NOT NULL AS FTA
    FROM DOL_FRAUD_DEMO.CURATED.OSHA_VIOLATION v
    JOIN DOL_FRAUD_DEMO.CURATED.EMPLOYER_XREF x ON x.SOURCE_SYSTEM = 'OSHA' AND x.SOURCE_KEY = TO_VARCHAR(v.ACTIVITY_NR)
    UNION ALL
    SELECT EMPLOYER_ID, ACTIVITY_NR, VIOL_TYPE, INITIAL_PENALTY, CURRENT_PENALTY, FAILURE_TO_ABATE
    FROM DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_OSHA_VIOLATION),
  vagg AS (
    SELECT EMPLOYER_ID, COUNT(DISTINCT ACTIVITY_NR) AS INSPECTIONS_WITH_CITATIONS,
           COUNT(*) AS CITATIONS, COUNT_IF(VIOL_TYPE = 'S') AS SERIOUS, COUNT_IF(VIOL_TYPE = 'W') AS WILLFUL,
           COUNT_IF(VIOL_TYPE = 'R') AS REPEAT_CITES, COUNT_IF(FTA) AS FAILURE_TO_ABATE,
           SUM(INITIAL_PENALTY) AS INITIAL_PENALTY, SUM(CURRENT_PENALTY) AS CURRENT_PENALTY
    FROM viol GROUP BY 1),
  fat AS (
    SELECT x.EMPLOYER_ID, COUNT(*) AS ACCIDENTS, COUNT_IF(a.FATALITY) AS FATALITY_ACCIDENTS
    FROM DOL_FRAUD_DEMO.CURATED.OSHA_ACCIDENT a
    JOIN DOL_FRAUD_DEMO.CURATED.EMPLOYER_XREF x ON x.SOURCE_SYSTEM = 'OSHA' AND x.SOURCE_KEY = TO_VARCHAR(a.ACTIVITY_NR)
    GROUP BY 1),
  ita AS (
    SELECT x.EMPLOYER_ID, MODE(LEFT(i.NAICS_CODE, 4)) AS NAICS4,
           SUM(i.ANNUAL_AVG_EMPLOYEES) AS ITA_EMPLOYEES, SUM(i.TOTAL_HOURS_WORKED) AS ITA_HOURS,
           SUM(i.DAFW_CASES + i.DJTR_CASES + i.OTHER_CASES) AS ITA_RECORDABLE_CASES,
           SUM(i.DAFW_CASES + i.DJTR_CASES) AS ITA_DART_CASES
    FROM DOL_FRAUD_DEMO.CURATED.ITA_300A i
    JOIN DOL_FRAUD_DEMO.CURATED.EMPLOYER_XREF x ON x.SOURCE_SYSTEM = 'ITA' AND x.SOURCE_KEY = TO_VARCHAR(i.ITA_ID)
    WHERE i.TOTAL_HOURS_WORKED >= 2000
    GROUP BY 1
    UNION ALL
    SELECT EMPLOYER_ID, '5613', ANNUAL_AVG_EMPLOYEES, TOTAL_HOURS_WORKED, DAFW_CASES + DJTR_CASES + OTHER_CASES, DAFW_CASES + DJTR_CASES
    FROM DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_ITA_300A),
  ita_rate AS (
    SELECT *, ITA_RECORDABLE_CASES * 200000 / NULLIF(ITA_HOURS, 0) AS ITA_TCR,
           MEDIAN(ITA_RECORDABLE_CASES * 200000 / NULLIF(ITA_HOURS, 0)) OVER (PARTITION BY NAICS4) AS PEER_MEDIAN_TCR,
           COUNT(*) OVER (PARTITION BY NAICS4) AS PEER_N
    FROM ita)
  SELECT COALESCE(v.EMPLOYER_ID, r.EMPLOYER_ID) AS EMPLOYER_ID,
         v.INSPECTIONS_WITH_CITATIONS, v.CITATIONS, v.SERIOUS, v.WILLFUL, v.REPEAT_CITES, v.FAILURE_TO_ABATE,
         v.INITIAL_PENALTY, v.CURRENT_PENALTY,
         1 - DIV0NULL(v.CURRENT_PENALTY, v.INITIAL_PENALTY) AS PENALTY_REDUCTION_PCT,
         f.ACCIDENTS, f.FATALITY_ACCIDENTS,
         r.ITA_EMPLOYEES, r.ITA_HOURS, r.ITA_RECORDABLE_CASES, r.ITA_TCR, r.PEER_MEDIAN_TCR, r.PEER_N,
         COALESCE(v.WILLFUL, 0) + COALESCE(v.REPEAT_CITES, 0) + COALESCE(v.FAILURE_TO_ABATE, 0) > 0 AS P5_WILLFUL_REPEAT_FTA,
         COALESCE(v.INITIAL_PENALTY, 0) >= 20000 AND (1 - DIV0NULL(v.CURRENT_PENALTY, v.INITIAL_PENALTY)) >= 0.5 AS P6_PENALTY_REDUCED,
         r.PEER_N >= 20 AND r.ITA_TCR < 0.4 * r.PEER_MEDIAN_TCR
           AND (COALESCE(v.SERIOUS, 0) >= 3 OR COALESCE(f.FATALITY_ACCIDENTS, 0) > 0) AS P7_POSSIBLE_UNDERREPORTING
  FROM vagg v
  FULL OUTER JOIN ita_rate r ON r.EMPLOYER_ID = v.EMPLOYER_ID
  LEFT JOIN fat f ON f.EMPLOYER_ID = COALESCE(v.EMPLOYER_ID, r.EMPLOYER_ID);

  -- OFLC (P4 offered wage well below the QCEW industry wage)
  CREATE OR REPLACE TABLE DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_OFLC_RISK
    COMMENT = 'Public: OFLC H-2A/H-2B program signals per resolved employer (plus fictional hero)' AS
  WITH cases AS (
    SELECT x.EMPLOYER_ID, o.PROGRAM, o.CASE_NUMBER, o.CASE_STATUS, o.WORKERS_CERTIFIED, o.WAGE_OFFER,
           o.WAGE_PER, o.WORKSITE_STATE, LEFT(o.NAICS_CODE, 3) AS NAICS3
    FROM DOL_FRAUD_DEMO.CURATED.OFLC_H2_CASES o
    JOIN DOL_FRAUD_DEMO.CURATED.EMPLOYER_XREF x ON x.SOURCE_SYSTEM = 'OFLC' AND x.SOURCE_KEY = o.CASE_NUMBER
    UNION ALL
    SELECT EMPLOYER_ID, PROGRAM, CASE_NUMBER, CASE_STATUS, WORKERS_CERTIFIED, WAGE_OFFER, WAGE_PER, WORKSITE_STATE, LEFT(NAICS_CODE, 3)
    FROM DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_OFLC_H2_CASE),
  bench AS (
    SELECT STATE_CODE, NAICS_CODE AS NAICS3, AVG_WEEKLY_WAGE / 40 AS QCEW_HOURLY
    FROM DOL_FRAUD_DEMO.CURATED.QCEW_STATE_INDUSTRY_2024 WHERE NAICS_DIGITS = 3)
  SELECT c.EMPLOYER_ID,
         COUNT(DISTINCT c.CASE_NUMBER) AS OFLC_CASES,
         COUNT_IF(c.PROGRAM = 'H-2A') AS H2A_CASES, COUNT_IF(c.PROGRAM = 'H-2B') AS H2B_CASES,
         SUM(c.WORKERS_CERTIFIED) AS WORKERS_CERTIFIED,
         MEDIAN(IFF(c.WAGE_PER ILIKE 'Hour%', c.WAGE_OFFER, NULL)) AS MEDIAN_HOURLY_OFFER,
         MEDIAN(b.QCEW_HOURLY) AS QCEW_HOURLY_BENCHMARK,
         DIV0NULL(MEDIAN(IFF(c.WAGE_PER ILIKE 'Hour%', c.WAGE_OFFER, NULL)), MEDIAN(b.QCEW_HOURLY)) AS OFFER_TO_BENCHMARK,
         COALESCE(DIV0NULL(MEDIAN(IFF(c.WAGE_PER ILIKE 'Hour%', c.WAGE_OFFER, NULL)), MEDIAN(b.QCEW_HOURLY)), 1) < 0.6 AS P4_WAGE_BELOW_BENCHMARK
  FROM cases c
  LEFT JOIN bench b ON b.STATE_CODE = c.WORKSITE_STATE AND b.NAICS3 = c.NAICS3
  GROUP BY 1;

  -- Risk 360 composite (P8 = signals in 2+ agencies)
  CREATE OR REPLACE TABLE DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360
    COMMENT = 'Employer Risk 360: composite of WHD, OSHA/ITA and OFLC signals. Risk indicators for demonstration only, not findings of violation or fraud.' AS
  WITH ui AS (
    SELECT LAST_EMPLOYER_ID AS EMPLOYER_ID, COUNT(*) AS UI_CLAIMS_CUR,
           COUNT_IF(R4_WORKING_WHILE_CLAIMING) AS UI_EXWORKER_WORKING_WHILE_CLAIMING,
           COUNT_IF(R5_FICTITIOUS_EMPLOYER) AS UI_FICTITIOUS_EMPLOYER_CLAIMS
    FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RULE_FLAGS GROUP BY 1),
  pay AS (
    SELECT EMPLOYER_ID, MAX_BY(DIV0NULL(FORM_1099_COUNT, W2_COUNT), TAX_YEAR) AS RATIO_1099_TO_W2
    FROM DOL_FRAUD_DEMO.RAW_SYNTH.EMPLOYER_PAYROLL_SUMMARY GROUP BY 1),
  peer AS (
    SELECT MEDIAN(RATIO_1099_TO_W2) AS PEER_RATIO
    FROM pay JOIN DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_EMPLOYER s USING (EMPLOYER_ID) WHERE s.ROLE = 'PEER'),
  base AS (
    -- Real names and EINs stay in CURATED.EMPLOYER_MASTER, where masking persists (11);
    -- this table is recreated weekly, so it carries only the pseudonymous DISPLAY_ID
    SELECT m.EMPLOYER_ID, m.DISPLAY_ID, m.STATE_CODE, m.CITY, m.ZIP5, m.NAICS_CODE, m.NAICS4,
           m.IS_SYNTHETIC, m.DATA_ORIGIN, m.MIN_MATCH_CONF,
           w.WHD_CASES, w.WHD_CASES_5YR, w.BACK_WAGES, w.EMPLOYEES_OWED, w.CMP_ASSESSED, w.BACK_WAGES_PER_EMPLOYEE,
           COALESCE(w.P1_REPEAT_VIOLATOR, FALSE) AS P1_REPEAT_VIOLATOR,
           COALESCE(w.P2_HIGH_BACK_WAGES, FALSE) AS P2_HIGH_BACK_WAGES,
           COALESCE(w.P3_H2A_VIOLATION, FALSE) AND COALESCE(f.OFLC_CASES, 0) > 0 AS P3_H2A_EMPLOYER_WITH_H2A_VIOLATION,
           f.OFLC_CASES, f.WORKERS_CERTIFIED, f.MEDIAN_HOURLY_OFFER, f.QCEW_HOURLY_BENCHMARK, f.OFFER_TO_BENCHMARK,
           COALESCE(f.P4_WAGE_BELOW_BENCHMARK, FALSE) AS P4_WAGE_BELOW_BENCHMARK,
           o.CITATIONS, o.SERIOUS, o.WILLFUL, o.REPEAT_CITES, o.FAILURE_TO_ABATE, o.INITIAL_PENALTY, o.CURRENT_PENALTY,
           o.PENALTY_REDUCTION_PCT, o.FATALITY_ACCIDENTS, o.ITA_TCR, o.PEER_MEDIAN_TCR,
           COALESCE(o.P5_WILLFUL_REPEAT_FTA, FALSE) AS P5_WILLFUL_REPEAT_FTA,
           COALESCE(o.P6_PENALTY_REDUCED, FALSE) AS P6_PENALTY_REDUCED,
           COALESCE(o.P7_POSSIBLE_UNDERREPORTING, FALSE) AS P7_POSSIBLE_UNDERREPORTING,
           -- synthetic-only signals (fictional employers; real employers stay NULL)
           IFF(m.IS_SYNTHETIC, pay.RATIO_1099_TO_W2, NULL) AS RATIO_1099_TO_W2,
           IFF(m.IS_SYNTHETIC, COALESCE(pay.RATIO_1099_TO_W2, 0) > 3 * (SELECT PEER_RATIO FROM peer), NULL) AS W1_MISCLASSIFICATION,
           IFF(m.IS_SYNTHETIC, ui.UI_EXWORKER_WORKING_WHILE_CLAIMING, NULL) AS UI_EXWORKER_WORKING_WHILE_CLAIMING,
           IFF(m.IS_SYNTHETIC, EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.RAW_SYNTH.SYNTH_EMPLOYER_LINK l WHERE l.TO_EMPLOYER_ID = m.EMPLOYER_ID), NULL) AS W3_POSSIBLE_SUCCESSOR
    FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_MASTER m
    LEFT JOIN DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_WHD_RISK w ON w.EMPLOYER_ID = m.EMPLOYER_ID
    LEFT JOIN DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_OFLC_RISK f ON f.EMPLOYER_ID = m.EMPLOYER_ID
    LEFT JOIN DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_OSHA_RISK o ON o.EMPLOYER_ID = m.EMPLOYER_ID
    LEFT JOIN pay ON pay.EMPLOYER_ID = m.EMPLOYER_ID
    LEFT JOIN ui ON ui.EMPLOYER_ID = m.EMPLOYER_ID
    WHERE w.EMPLOYER_ID IS NOT NULL OR f.EMPLOYER_ID IS NOT NULL OR o.EMPLOYER_ID IS NOT NULL OR m.IS_SYNTHETIC)
  SELECT b.*,
         IFF(P1_REPEAT_VIOLATOR OR P2_HIGH_BACK_WAGES OR P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 1, 0)
           + IFF(P5_WILLFUL_REPEAT_FTA OR P6_PENALTY_REDUCED OR P7_POSSIBLE_UNDERREPORTING, 1, 0)
           + IFF(P4_WAGE_BELOW_BENCHMARK OR P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 1, 0) AS AGENCIES_FLAGGED,
         ARRAY_COMPACT(ARRAY_CONSTRUCT(
           IFF(P1_REPEAT_VIOLATOR OR P2_HIGH_BACK_WAGES OR P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 'WHD', NULL),
           IFF(P5_WILLFUL_REPEAT_FTA OR P6_PENALTY_REDUCED OR P7_POSSIBLE_UNDERREPORTING, 'OSHA', NULL),
           IFF(P4_WAGE_BELOW_BENCHMARK OR P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 'OFLC', NULL))) AS AGENCY_LIST,
         LEAST(100, ROUND(
             12 * IFF(P1_REPEAT_VIOLATOR, 1, 0) + 10 * IFF(P2_HIGH_BACK_WAGES, 1, 0)
           + 14 * IFF(P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 1, 0) + 10 * IFF(P4_WAGE_BELOW_BENCHMARK, 1, 0)
           + 12 * IFF(P5_WILLFUL_REPEAT_FTA, 1, 0) + 6 * IFF(P6_PENALTY_REDUCED, 1, 0)
           + 12 * IFF(P7_POSSIBLE_UNDERREPORTING, 1, 0)
           + 6 * LEAST(COALESCE(WHD_CASES_5YR, 0), 3) + 4 * LEAST(COALESCE(FATALITY_ACCIDENTS, 0), 2)
           + 8 * IFF(COALESCE(W1_MISCLASSIFICATION, FALSE), 1, 0) + 6 * IFF(COALESCE(W3_POSSIBLE_SUCCESSOR, FALSE), 1, 0)
           + 4 * LEAST(COALESCE(UI_EXWORKER_WORKING_WHILE_CLAIMING, 0) / 25, 2))) AS RISK_SCORE,
         ARRAY_COMPACT(ARRAY_CONSTRUCT(
           IFF(P1_REPEAT_VIOLATOR, 'WHD repeat violator (' || COALESCE(WHD_CASES_5YR, 0) || ' cases in 5 yrs)', NULL),
           IFF(P2_HIGH_BACK_WAGES, 'Back wages per employee 2+ std dev above NAICS peers', NULL),
           IFF(P3_H2A_EMPLOYER_WITH_H2A_VIOLATION, 'H-2A employer with WHD H-2A violations', NULL),
           IFF(P4_WAGE_BELOW_BENCHMARK, 'Offered wage ' || ROUND(OFFER_TO_BENCHMARK * 100) || '% of QCEW industry wage', NULL),
           IFF(P5_WILLFUL_REPEAT_FTA, 'OSHA willful, repeat or failure-to-abate citations', NULL),
           IFF(P6_PENALTY_REDUCED, 'OSHA penalties reduced ' || ROUND(PENALTY_REDUCTION_PCT * 100) || '%', NULL),
           IFF(P7_POSSIBLE_UNDERREPORTING, 'ITA injury rate ' || ROUND(ITA_TCR, 2) || ' vs peer median ' || ROUND(PEER_MEDIAN_TCR, 2) || ' with serious citations', NULL),
           IFF(W1_MISCLASSIFICATION, '1099-to-W-2 ratio ' || ROUND(RATIO_1099_TO_W2, 1) || 'x (synthetic)', NULL),
           IFF(W3_POSSIBLE_SUCCESSOR, 'Possible successor to a debarred employer (synthetic)', NULL),
           IFF(UI_EXWORKER_WORKING_WHILE_CLAIMING > 0, UI_EXWORKER_WORKING_WHILE_CLAIMING || ' ex-workers flagged working while claiming (synthetic)', NULL)))
           AS TOP_REASONS
  FROM base b;

  RETURN 'Employer risk rebuilt: ' || (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360) || ' employers';
END;
$$;

