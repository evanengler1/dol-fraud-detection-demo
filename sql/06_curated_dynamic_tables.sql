-- Rules vs seeded labels (precision/recall per rule)
SELECT rule, COUNT_IF(flag) AS flagged, COUNT_IF(flag AND f.IS_FRAUD) AS true_pos,
       ROUND(DIV0(COUNT_IF(flag AND f.IS_FRAUD), COUNT_IF(flag)) * 100, 1) AS precision_pct
FROM (
  SELECT CLAIM_ID, 'R1 shared bank' AS rule, R1_SHARED_BANK_ACCOUNT AS flag FROM DT_CLAIM_RULE_FLAGS
  UNION ALL SELECT CLAIM_ID, 'R2 device/IP farm', R2_DEVICE_OR_IP_FARM FROM DT_CLAIM_RULE_FLAGS
  UNION ALL SELECT CLAIM_ID, 'R3 multi-state SSN', R3_MULTI_STATE_SSN FROM DT_CLAIM_RULE_FLAGS
  UNION ALL SELECT CLAIM_ID, 'R4 working while claiming', R4_WORKING_WHILE_CLAIMING FROM DT_CLAIM_RULE_FLAGS
  UNION ALL SELECT CLAIM_ID, 'R5 fictitious employer', R5_FICTITIOUS_EMPLOYER FROM DT_CLAIM_RULE_FLAGS
  UNION ALL SELECT CLAIM_ID, 'R6 synthetic identity', R6_SYNTHETIC_IDENTITY FROM DT_CLAIM_RULE_FLAGS) r
JOIN DT_CLAIM_FEATURES f USING (CLAIM_ID)
GROUP BY 1 ORDER BY 1;

-- Cross-agency employers (real + hero)
SELECT AGENCIES_FLAGGED, COUNT(*) AS employers, COUNT_IF(IS_SYNTHETIC) AS synthetic
FROM EMPLOYER_RISK_360 GROUP BY 1 ORDER BY 1;

SELECT DISPLAY_ID, STATE_CODE, NAICS4, RISK_SCORE, AGENCY_LIST, TOP_REASONS
FROM EMPLOYER_RISK_360 ORDER BY RISK_SCORE DESC LIMIT 10;
