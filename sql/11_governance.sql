-- -----------------------------------------------------------------------------
-- 5. Row access: state partners see only their state
-- -----------------------------------------------------------------------------
CREATE TABLE IF NOT EXISTS ROLE_STATE_ACCESS (ROLE_NAME VARCHAR, STATE_CODE VARCHAR(2))
  COMMENT = 'Row access mapping: which states a partner role may see';
MERGE INTO ROLE_STATE_ACCESS t USING (SELECT 'DOL_STATE_PARTNER_TX' AS ROLE_NAME, 'TX' AS STATE_CODE) s
  ON t.ROLE_NAME = s.ROLE_NAME AND t.STATE_CODE = s.STATE_CODE
  WHEN NOT MATCHED THEN INSERT VALUES (s.ROLE_NAME, s.STATE_CODE);

CREATE ROW ACCESS POLICY IF NOT EXISTS RAP_CLAIM_STATE AS (STATE_CODE VARCHAR) RETURNS BOOLEAN -> TRUE
  COMMENT = 'Roles listed in ROLE_STATE_ACCESS see only their mapped states; all other roles are unrestricted';
ALTER ROW ACCESS POLICY RAP_CLAIM_STATE SET BODY ->
  CURRENT_ROLE() NOT IN (SELECT ROLE_NAME FROM DOL_FRAUD_DEMO.GOVERNANCE.ROLE_STATE_ACCESS)
  OR EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ROLE_STATE_ACCESS a
             WHERE a.ROLE_NAME = CURRENT_ROLE() AND a.STATE_CODE = STATE_CODE);

EXECUTE IMMEDIATE $$
BEGIN
  ALTER TABLE DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM DROP ALL ROW ACCESS POLICIES;
  ALTER TABLE DOL_FRAUD_DEMO.RAW_SYNTH.UI_CLAIM ADD ROW ACCESS POLICY DOL_FRAUD_DEMO.GOVERNANCE.RAP_CLAIM_STATE ON (STATE_CODE);
  ALTER DYNAMIC TABLE DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RULE_FLAGS DROP ALL ROW ACCESS POLICIES;
