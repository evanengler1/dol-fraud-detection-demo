-- -----------------------------------------------------------------------------
-- 4. Masking policies
-- CURRENT_ROLE() keeps persona demos predictable (secondary roles do not unmask)
-- -----------------------------------------------------------------------------
-- Policies attached to columns cannot be replaced, so create once and update
-- the body on reruns (CREATE IF NOT EXISTS + ALTER ... SET BODY)
CREATE MASKING POLICY IF NOT EXISTS MP_SSN AS (V VARCHAR) RETURNS VARCHAR -> NULL
  COMMENT = 'SSN: full for the owner role, last 4 for UI analysts and state partners';
ALTER MASKING POLICY MP_SSN SET BODY ->
  CASE WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN') THEN V
       WHEN CURRENT_ROLE() IN ('DOL_OUI_ANALYST', 'DOL_STATE_PARTNER_TX') THEN 'XXX-XX-' || RIGHT(V, 4)
       ELSE '***-**-****' END;

CREATE MASKING POLICY IF NOT EXISTS MP_BANK_ACCOUNT AS (V VARCHAR) RETURNS VARCHAR -> NULL
  COMMENT = 'Bank account: last 4 for UI analysts and OIG, so shared-account rings stay visible';
ALTER MASKING POLICY MP_BANK_ACCOUNT SET BODY ->
  CASE WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN') THEN V
       WHEN CURRENT_ROLE() IN ('DOL_OUI_ANALYST', 'DOL_OIG_EXECUTIVE') THEN REPEAT('*', GREATEST(LENGTH(V) - 4, 0)) || RIGHT(V, 4)
       ELSE '****' END;

CREATE MASKING POLICY IF NOT EXISTS MP_PII_STRING AS (V VARCHAR) RETURNS VARCHAR -> NULL
  COMMENT = 'Claimant names and contact details';
ALTER MASKING POLICY MP_PII_STRING SET BODY ->
  CASE WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN', 'DOL_OUI_ANALYST') THEN V
       WHEN CURRENT_ROLE() = 'DOL_STATE_PARTNER_TX' THEN LEFT(V, 1) || '***'
       ELSE '[REDACTED]' END;

CREATE MASKING POLICY IF NOT EXISTS MP_DOB AS (V DATE) RETURNS DATE -> NULL
  COMMENT = 'Date of birth: year only outside the UI analyst role';
ALTER MASKING POLICY MP_DOB SET BODY ->
  CASE WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN', 'DOL_OUI_ANALYST') THEN V
       ELSE DATE_FROM_PARTS(YEAR(V), 1, 1) END;

CREATE MASKING POLICY IF NOT EXISTS MP_EMPLOYER_NAME AS (V VARCHAR, IS_SYNTHETIC BOOLEAN) RETURNS VARCHAR -> NULL
  COMMENT = 'Real employer names are not shown in the demo; use DISPLAY_ID';
ALTER MASKING POLICY MP_EMPLOYER_NAME SET BODY ->
  CASE WHEN IS_SYNTHETIC THEN V
       WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN') THEN V
       ELSE '[EMPLOYER NAME WITHHELD]' END;

CREATE MASKING POLICY IF NOT EXISTS MP_EIN AS (V VARCHAR, IS_SYNTHETIC BOOLEAN) RETURNS VARCHAR -> NULL
  COMMENT = 'EIN: last 4 for WHD investigators and OIG';
ALTER MASKING POLICY MP_EIN SET BODY ->
  CASE WHEN IS_SYNTHETIC THEN V
       WHEN CURRENT_ROLE() IN ('DOL_FRAUD_DEMO_ROLE', 'ACCOUNTADMIN', 'DOL_WHD_INVESTIGATOR', 'DOL_OIG_EXECUTIVE') THEN 'XX-XXX' || RIGHT(V, 4)
