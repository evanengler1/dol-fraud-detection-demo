-- Who read sensitive columns, last 7 days (ACCOUNT_USAGE has up to ~3h latency)
SELECT ah.QUERY_START_TIME, ah.USER_NAME, q.ROLE_NAME,
       obj.value:"objectName"::STRING AS OBJECT_NAME, col.value:"columnName"::STRING AS COLUMN_NAME
FROM SNOWFLAKE.ACCOUNT_USAGE.ACCESS_HISTORY ah
JOIN SNOWFLAKE.ACCOUNT_USAGE.QUERY_HISTORY q ON q.QUERY_ID = ah.QUERY_ID,
     LATERAL FLATTEN(INPUT => ah.BASE_OBJECTS_ACCESSED) obj,
     LATERAL FLATTEN(INPUT => obj.value:"columns") col
WHERE ah.QUERY_START_TIME >= DATEADD(day, -7, CURRENT_TIMESTAMP())
  AND obj.value:"objectName"::STRING ILIKE 'DOL_FRAUD_DEMO.%'
  AND col.value:"columnName"::STRING IN ('SSN', 'BANK_ACCOUNT', 'CANONICAL_NAME', 'EIN')
ORDER BY ah.QUERY_START_TIME DESC
LIMIT 100;

