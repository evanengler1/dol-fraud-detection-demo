-- =============================================================================
-- DOL Fraud Detection Demo - 12 Alerts
--   ALERT_NEW_FRAUD_RING      : a new shared-attribute cluster of 5+ claims appears
--   ALERT_CLAIMS_SURGE        : a state's initial claims exceed the anomaly band
--   ALERT_HIGH_RISK_EMPLOYER  : an employer newly reaches signals in 3 agencies
-- Each alert writes to GOVERNANCE.ALERT_LOG (always) and can e-mail through
-- SYSTEM$SEND_EMAIL if an email integration is configured (optional, below).
-- Alerts are created SUSPENDED; resume them for a live demo and suspend after.
-- =============================================================================

USE ROLE DOL_FRAUD_DEMO_ROLE;
USE WAREHOUSE DOL_FRAUD_WH;
USE SCHEMA DOL_FRAUD_DEMO.GOVERNANCE;

CREATE TABLE IF NOT EXISTS ALERT_LOG (
  ALERT_NAME VARCHAR, FIRED_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP(),
  SUBJECT_KEY VARCHAR, DETAIL VARIANT
) COMMENT = 'Alert firings for the DOL fraud demo (synthetic claims and public employer data)';

-- Watermark of what has already been alerted, so alerts fire only on new items
CREATE TABLE IF NOT EXISTS ALERT_SEEN (ALERT_NAME VARCHAR, SUBJECT_KEY VARCHAR, SEEN_AT TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP())
  COMMENT = 'Items already alerted on';

-- Seed the watermark with today's state so the first run does not flood the log
INSERT INTO ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
SELECT 'NEW_FRAUD_RING', LINK_TYPE || ':' || LINK_VALUE FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RING_STATS
WHERE CLAIM_COUNT >= 5
  AND LINK_TYPE || ':' || LINK_VALUE NOT IN (SELECT SUBJECT_KEY FROM ALERT_SEEN WHERE ALERT_NAME = 'NEW_FRAUD_RING');
INSERT INTO ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
SELECT 'HIGH_RISK_EMPLOYER', EMPLOYER_ID FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360
WHERE AGENCIES_FLAGGED = 3
  AND EMPLOYER_ID NOT IN (SELECT SUBJECT_KEY FROM ALERT_SEEN WHERE ALERT_NAME = 'HIGH_RISK_EMPLOYER');
INSERT INTO ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
SELECT 'CLAIMS_SURGE', STATE_CODE || ':' || TO_VARCHAR(WEEK_ENDING) FROM DOL_FRAUD_DEMO.ML.V_CLAIMS_SURGE_ALERTS
WHERE STATE_CODE || ':' || TO_VARCHAR(WEEK_ENDING) NOT IN (SELECT SUBJECT_KEY FROM ALERT_SEEN WHERE ALERT_NAME = 'CLAIMS_SURGE');

-- New fraud ring (synthetic claims) ---------------------------------------------
EXECUTE IMMEDIATE $$
CREATE OR REPLACE ALERT ALERT_NEW_FRAUD_RING
  WAREHOUSE = DOL_FRAUD_WH
  SCHEDULE = '15 MINUTE'
  COMMENT = 'Fires when a new cluster of 5+ current claims shares a bank account, device, IP or phone'
  IF (EXISTS (
    SELECT 1 FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RING_STATS r
    WHERE r.CLAIM_COUNT >= 5
      AND NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'NEW_FRAUD_RING' AND s.SUBJECT_KEY = r.LINK_TYPE || ':' || r.LINK_VALUE)))
  THEN
  BEGIN
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG (ALERT_NAME, SUBJECT_KEY, DETAIL)
    SELECT 'NEW_FRAUD_RING', r.LINK_TYPE || ':' || r.LINK_VALUE,
           OBJECT_CONSTRUCT('claims', r.CLAIM_COUNT, 'states', r.STATES, 'paid', r.TOTAL_PAID)
    FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RING_STATS r
    WHERE r.CLAIM_COUNT >= 5
      AND NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'NEW_FRAUD_RING' AND s.SUBJECT_KEY = r.LINK_TYPE || ':' || r.LINK_VALUE);
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
    SELECT 'NEW_FRAUD_RING', SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG
    WHERE ALERT_NAME = 'NEW_FRAUD_RING'
      AND SUBJECT_KEY NOT IN (SELECT SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN WHERE ALERT_NAME = 'NEW_FRAUD_RING');
  END;
$$;

-- State claims surge (public ETA 539) -------------------------------------------
EXECUTE IMMEDIATE $$
CREATE OR REPLACE ALERT ALERT_CLAIMS_SURGE
  WAREHOUSE = DOL_FRAUD_WH
  SCHEDULE = 'USING CRON 0 9 * * 4 America/New_York'
  COMMENT = 'Weekly (ETA 539 posts Thursdays): fires when a state week exceeds the anomaly model upper bound'
  IF (EXISTS (
    SELECT 1 FROM DOL_FRAUD_DEMO.ML.V_CLAIMS_SURGE_ALERTS v
    WHERE NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'CLAIMS_SURGE' AND s.SUBJECT_KEY = v.STATE_CODE || ':' || TO_VARCHAR(v.WEEK_ENDING))))
  THEN
  BEGIN
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG (ALERT_NAME, SUBJECT_KEY, DETAIL)
    SELECT 'CLAIMS_SURGE', v.STATE_CODE || ':' || TO_VARCHAR(v.WEEK_ENDING),
           OBJECT_CONSTRUCT('initial_claims', v.INITIAL_CLAIMS, 'forecast', v.FORECAST, 'multiple', v.SURGE_MULTIPLE, 'severity', v.SEVERITY)
    FROM DOL_FRAUD_DEMO.ML.V_CLAIMS_SURGE_ALERTS v
    WHERE NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'CLAIMS_SURGE' AND s.SUBJECT_KEY = v.STATE_CODE || ':' || TO_VARCHAR(v.WEEK_ENDING));
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
    SELECT 'CLAIMS_SURGE', SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG
    WHERE ALERT_NAME = 'CLAIMS_SURGE'
      AND SUBJECT_KEY NOT IN (SELECT SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN WHERE ALERT_NAME = 'CLAIMS_SURGE');
  END;
$$;

-- Employer newly flagged by all three agencies --------------------------------
EXECUTE IMMEDIATE $$
CREATE OR REPLACE ALERT ALERT_HIGH_RISK_EMPLOYER
  WAREHOUSE = DOL_FRAUD_WH
  SCHEDULE = 'USING CRON 0 7 * * 1 America/New_York'
  COMMENT = 'Weekly, after the employer risk rebuild: fires when an employer newly has signals from WHD, OSHA and OFLC'
  IF (EXISTS (
    SELECT 1 FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360 e
    WHERE e.AGENCIES_FLAGGED = 3
      AND NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'HIGH_RISK_EMPLOYER' AND s.SUBJECT_KEY = e.EMPLOYER_ID)))
  THEN
  BEGIN
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG (ALERT_NAME, SUBJECT_KEY, DETAIL)
    SELECT 'HIGH_RISK_EMPLOYER', e.EMPLOYER_ID,
           OBJECT_CONSTRUCT('display_id', e.DISPLAY_ID, 'risk_score', e.RISK_SCORE, 'reasons', e.TOP_REASONS)
    FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360 e
    WHERE e.AGENCIES_FLAGGED = 3
      AND NOT EXISTS (SELECT 1 FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN s
                      WHERE s.ALERT_NAME = 'HIGH_RISK_EMPLOYER' AND s.SUBJECT_KEY = e.EMPLOYER_ID);
    INSERT INTO DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN (ALERT_NAME, SUBJECT_KEY)
    SELECT 'HIGH_RISK_EMPLOYER', SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_LOG
    WHERE ALERT_NAME = 'HIGH_RISK_EMPLOYER'
      AND SUBJECT_KEY NOT IN (SELECT SUBJECT_KEY FROM DOL_FRAUD_DEMO.GOVERNANCE.ALERT_SEEN WHERE ALERT_NAME = 'HIGH_RISK_EMPLOYER');
  END;
$$;

