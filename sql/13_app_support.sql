USE ROLE DOL_FRAUD_DEMO_ROLE;
USE WAREHOUSE DOL_FRAUD_WH;
USE SCHEMA DOL_FRAUD_DEMO.APP;

-- Analyst decisions on claims and employers (write-back from the app)
CREATE TABLE IF NOT EXISTS CASE_ACTIONS (
  ACTION_ID      VARCHAR DEFAULT UUID_STRING(),
  SUBJECT_TYPE   VARCHAR,         -- CLAIM | EMPLOYER | RING
  SUBJECT_ID     VARCHAR,         -- CLAIM_ID, EMPLOYER_ID or LINK_TYPE:LINK_VALUE
  ACTION         VARCHAR,         -- REFER_OIG | REFER_WHD | REFER_OSHA | HOLD_PAYMENT | REQUEST_ID_VERIFICATION | CLEAR | NOTE
  NOTE           VARCHAR,
  ACTED_BY       VARCHAR DEFAULT CURRENT_USER(),
  ACTED_ROLE     VARCHAR DEFAULT CURRENT_ROLE(),
  ACTED_AT       TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Analyst triage decisions recorded by the demo app. Demonstration records only.';

-- Cross-agency referrals (one row per referral, status tracked)
CREATE TABLE IF NOT EXISTS REFERRALS (
  REFERRAL_ID    VARCHAR DEFAULT UUID_STRING(),
  EMPLOYER_ID    VARCHAR,
  FROM_AGENCY    VARCHAR,
  TO_AGENCY      VARCHAR,         -- WHD | OSHA | OFLC | OIG | STATE_UI
  REASON         VARCHAR,
  STATUS         VARCHAR DEFAULT 'OPEN',
  CREATED_BY     VARCHAR DEFAULT CURRENT_USER(),
  CREATED_AT     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Cross-agency referrals created in the demo app. Demonstration records only.';

-- Analyst feedback on model scores (for retraining and drift review)
CREATE TABLE IF NOT EXISTS MODEL_FEEDBACK (
  CLAIM_ID       VARCHAR,
  ML_PROBABILITY FLOAT,
  ANALYST_LABEL  VARCHAR,         -- CONFIRMED_FRAUD | NOT_FRAUD | UNSURE
  NOTE           VARCHAR,
  CREATED_BY     VARCHAR DEFAULT CURRENT_USER(),
  CREATED_AT     TIMESTAMP_LTZ DEFAULT CURRENT_TIMESTAMP()
) COMMENT = 'Analyst feedback on ML claim scores. Demonstration records only.';

-- Headline KPIs for the landing page (one row)
CREATE OR REPLACE VIEW V_KPI_HEADLINE COMMENT = 'Landing page KPIs; each value is labeled public or synthetic in the app' AS
SELECT
  (SELECT SUM(FRAUD_DOLLARS) FROM DOL_FRAUD_DEMO.ANALYTICS.DT_STATE_UI_BASELINE
     WHERE YEAR(QUARTER_ENDING) = YEAR(CURRENT_DATE()) - 1)                         AS PUBLIC_FRAUD_OP_LAST_FULL_YEAR,
  (SELECT MAX(FRAUD_RATE) FROM DOL_FRAUD_DEMO.CURATED.BAM_INTEGRITY_RATES
     WHERE STATE_CODE = 'US')                                                        AS PUBLIC_BAM_PEAK_FRAUD_RATE,
  (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ML.V_CLAIMS_SURGE_ALERTS WHERE SEVERITY = 'SEVERE') AS PUBLIC_SEVERE_SURGE_WEEKS,
  (SELECT COUNT_IF(AGENCIES_FLAGGED >= 2) FROM DOL_FRAUD_DEMO.ANALYTICS.EMPLOYER_RISK_360 WHERE NOT IS_SYNTHETIC) AS PUBLIC_CROSS_AGENCY_EMPLOYERS,
  (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.CURATED.EMPLOYER_MASTER WHERE NOT IS_SYNTHETIC) AS PUBLIC_RESOLVED_EMPLOYERS,
  (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ANALYTICS.V_CLAIM_RISK)                       AS SYNTH_CURRENT_CLAIMS,
  (SELECT COUNT_IF(PRIORITY_SCORE >= 50) FROM DOL_FRAUD_DEMO.ANALYTICS.V_CLAIM_RISK) AS SYNTH_FLAGGED_CLAIMS,
  (SELECT SUM(IFF(PRIORITY_SCORE >= 50, AMOUNT_PAID, 0)) FROM DOL_FRAUD_DEMO.ANALYTICS.V_CLAIM_RISK) AS SYNTH_DOLLARS_AT_RISK,
  (SELECT COUNT_IF(DETECTION_SOURCE = 'ML_ONLY') FROM DOL_FRAUD_DEMO.ANALYTICS.V_CLAIM_RISK) AS SYNTH_ML_ONLY_CATCHES,
  (SELECT COUNT(*) FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RING_STATS WHERE CLAIM_COUNT >= 5) AS SYNTH_RINGS;

-- Ring graph for the network view: nodes are claims, edges are shared attributes
CREATE OR REPLACE VIEW V_RING_GRAPH_EDGES COMMENT = 'Synthetic data. Edges for the fraud ring network view (clusters of 5+ claims only)' AS
SELECT l.CLAIM_ID_A, l.CLAIM_ID_B, l.LINK_TYPE, r.LINK_TYPE || ':' || r.LINK_VALUE AS RING_KEY, r.CLAIM_COUNT, r.STATE_COUNT
FROM DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_LINKS l
JOIN DOL_FRAUD_DEMO.ANALYTICS.DT_CLAIM_RING_STATS r ON r.LINK_TYPE = l.LINK_TYPE AND r.LINK_VALUE = l.LINK_VALUE
WHERE r.CLAIM_COUNT >= 5;

SELECT * FROM V_KPI_HEADLINE;
